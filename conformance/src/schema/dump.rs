// Ports: contracts/tools/schemadump/main.go (dumpSQLite, dumpMySQL, dumpMongo, the FT.INFO write) and contracts/tools/dump-schemas.sh (pg_dump_clean) @ WP-2-13.

//! Dumps a database's schema the way the Go tool does, so that a Rust store's
//! database and the Go store's database are read by the same code.
//!
//! The formats are the Go tool's: the same header lines, the same statement per
//! table in name order, the same JSON for MongoDB (see [`super::gojson`]). The
//! PostgreSQL dump is `pg_dump -s` run inside the server's container, filtered as
//! `dump-schemas.sh` filters it.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;
use std::process::Command;

use mongodb::Client;
use mongodb::bson::{Bson, Document, doc};
use rusqlite::OpenFlags;
use sqlx::{AssertSqlSafe, Connection as _, MySqlConnection, Row as _};

use super::gojson::{self, Value};
use super::{Result, fail, mysql_options};

/// The first line of every dump the Go tool writes.
pub const GO_HEADER: &str =
    "-- Generated by contracts/tools/schemadump from the Go implementation. Do not edit.";

/// The first line of every PostgreSQL dump, written by `dump-schemas.sh`.
pub const POSTGRES_HEADER: &str = "-- Generated by contracts/tools/dump-schemas.sh (pg_dump -s) from the Go implementation. Do not edit.";

/// The `_generated` line of a MongoDB dump.
const MONGO_GENERATED: &str = "contracts/tools/schemadump from the Go implementation. Do not edit.";

/// The SQLite dump of `dumpSQLite`: every schema object's statement, grouped by
/// table.
pub fn sqlite(path: &Path) -> Result<String> {
    let conn = rusqlite::Connection::open_with_flags(path, OpenFlags::SQLITE_OPEN_READ_ONLY)
        .map_err(fail)?;
    let mut statement = conn
        .prepare(
            "SELECT type, name, tbl_name, sql FROM sqlite_master \
             WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' \
             ORDER BY tbl_name, type DESC, name",
        )
        .map_err(fail)?;
    let rows = statement
        .query_map([], |row| {
            Ok((
                row.get::<_, String>(0)?,
                row.get::<_, String>(1)?,
                row.get::<_, String>(2)?,
                row.get::<_, String>(3)?,
            ))
        })
        .map_err(fail)?;
    let mut out = format!("{GO_HEADER}\n");
    for row in rows {
        let (kind, name, table, sql) = row.map_err(fail)?;
        let _ = write!(out, "\n-- {kind} {name} (table {table})\n{sql};\n");
    }
    Ok(out)
}

/// The MySQL or MariaDB dump of `dumpMySQL`: the server version, then every
/// table's `SHOW CREATE TABLE` in name order. `dsn` names the database, as in
/// `root:password@tcp(127.0.0.1:3306)/gorse_schema_data?parseTime=true`.
pub async fn mysql(dsn: &str) -> Result<String> {
    let mut conn = MySqlConnection::connect_with(&mysql_options(dsn)?)
        .await
        .map_err(fail)?;
    let (version,): (String,) = sqlx::query_as("SELECT VERSION()")
        .fetch_one(&mut conn)
        .await
        .map_err(fail)?;
    let rows = sqlx::query("SHOW TABLES")
        .fetch_all(&mut conn)
        .await
        .map_err(fail)?;
    let mut tables = rows
        .iter()
        .map(|row| row.try_get::<String, _>(0))
        .collect::<std::result::Result<Vec<_>, _>>()
        .map_err(fail)?;
    tables.sort();
    let mut out = format!("{GO_HEADER}\n-- Server: MySQL {version}\n");
    for table in tables {
        let row = sqlx::query(AssertSqlSafe(format!("SHOW CREATE TABLE `{table}`")))
            .fetch_one(&mut conn)
            .await
            .map_err(fail)?;
        let create: String = row.try_get(1).map_err(fail)?;
        let _ = write!(out, "\n{create};\n");
    }
    conn.close().await.map_err(fail)?;
    Ok(out)
}

/// The PostgreSQL dump of `dump-schemas.sh`: `pg_dump -s` inside `container`,
/// with the header lines the script writes.
pub fn postgres(container: &str, database: &str) -> Result<String> {
    let version = docker(&["exec", container, "postgres", "--version"])?;
    let dump = docker(&[
        "exec",
        container,
        "pg_dump",
        "-s",
        "--no-owner",
        "--no-privileges",
        "-U",
        "gorse",
        database,
    ])?;
    Ok(format!(
        "{POSTGRES_HEADER}\n-- Server: {}\n{}",
        version.trim_end(),
        pg_clean(&dump)
    ))
}

/// Runs `docker` with `args` and returns its standard output.
fn docker(args: &[&str]) -> Result<String> {
    let output = Command::new("docker").args(args).output().map_err(fail)?;
    if !output.status.success() {
        return Err(fail(format!(
            "docker {}: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr)
        )));
    }
    Ok(String::from_utf8_lossy(&output.stdout).into_owned())
}

/// The filter `dump-schemas.sh` applies to `pg_dump -s`: it drops the `SET`
/// lines, the `SELECT pg_catalog` lines, the bare `--` and the header comments
/// pg_dump writes, the `plpgsql` lines and the extension names, then squeezes
/// runs of blank lines as `cat -s` does.
pub fn pg_clean(dump: &str) -> String {
    let mut out = String::new();
    let mut blank = false;
    for line in dump.lines() {
        if is_pg_noise(line) {
            continue;
        }
        if line.is_empty() {
            if blank {
                continue;
            }
            blank = true;
        } else {
            blank = false;
        }
        out.push_str(line);
        out.push('\n');
    }
    out
}

fn is_pg_noise(line: &str) -> bool {
    line.starts_with("SET ")
        || line.starts_with("SELECT pg_catalog")
        || line == "--"
        || line.starts_with("-- Dumped")
        || line.starts_with("-- PostgreSQL database dump")
        || line.contains("plpgsql")
        || line.starts_with("-- Name: EXTENSION")
}

/// The MongoDB dump of `dumpMongo`: every collection's name, type and options,
/// and its indexes without the index format version, each list sorted by name.
/// `uri` names the server without a database.
pub async fn mongodb(uri: &str, database: &str) -> Result<String> {
    let client = Client::with_uri_str(uri).await.map_err(fail)?;
    let db = client.database(database);
    let mut specs = first_batch(
        &db.run_command(doc! { "listCollections": 1 })
            .await
            .map_err(fail)?,
    )?;
    specs.sort_by(|a, b| name_of(a).cmp(name_of(b)));
    let mut collections = Vec::new();
    for spec in &specs {
        let name = name_of(spec).to_owned();
        let kind = spec.get_str("type").unwrap_or("collection").to_owned();
        let options = spec.get_document("options").cloned().unwrap_or_default();
        let reply = db
            .run_command(doc! { "listIndexes": name.as_str() })
            .await
            .map_err(fail)?;
        let mut indexes = first_batch(&reply)?;
        for index in &mut indexes {
            index.remove("v");
        }
        indexes.sort_by(|a, b| name_of(a).cmp(name_of(b)));
        let indexes = indexes
            .iter()
            .map(|index| bson_json(&Bson::Document(index.clone())))
            .collect::<Result<Vec<_>>>()?;
        collections.push(Value::Object(BTreeMap::from([
            ("name".to_owned(), Value::String(name)),
            ("type".to_owned(), Value::String(kind)),
            ("options".to_owned(), bson_json(&Bson::Document(options))?),
            ("indexes".to_owned(), Value::Array(indexes)),
        ])));
    }
    let root = Value::Object(BTreeMap::from([
        (
            "_generated".to_owned(),
            Value::String(MONGO_GENERATED.to_owned()),
        ),
        ("collections".to_owned(), Value::Array(collections)),
    ]));
    Ok(format!(
        "{}\n",
        gojson::marshal_indent(&root).map_err(fail)?
    ))
}

/// The `name` field of a listing entry, or the empty string when it has none.
fn name_of(document: &Document) -> &str {
    document.get_str("name").unwrap_or_default()
}

/// The documents of a command reply's first batch.
fn first_batch(reply: &Document) -> Result<Vec<Document>> {
    let batch = reply
        .get_document("cursor")
        .and_then(|cursor| cursor.get_array("firstBatch"))
        .map_err(fail)?;
    batch
        .iter()
        .map(|item| match item {
            Bson::Document(document) => Ok(document.clone()),
            other => Err(fail(format!("unexpected entry in a batch: {other:?}"))),
        })
        .collect()
}

/// A BSON value as the Go tool's `json.Marshal` writes it after decoding into
/// `bson.M`. Only the types that schema documents hold are written; any other
/// type is an error rather than a guess.
fn bson_json(value: &Bson) -> Result<Value> {
    Ok(match value {
        Bson::Double(f) => Value::Float(*f),
        Bson::String(s) => Value::String(s.clone()),
        Bson::Boolean(b) => Value::Bool(*b),
        Bson::Null => Value::Null,
        Bson::Int32(n) => Value::Int(i64::from(*n)),
        Bson::Int64(n) => Value::Int(*n),
        Bson::ObjectId(id) => Value::String(id.to_hex()),
        Bson::Array(items) => Value::Array(items.iter().map(bson_json).collect::<Result<_>>()?),
        Bson::Document(document) => Value::Object(
            document
                .iter()
                .map(|(key, item)| Ok((key.clone(), bson_json(item)?)))
                .collect::<Result<_>>()?,
        ),
        other => {
            return Err(fail(format!(
                "no dump for BSON type {:?}",
                other.element_type()
            )));
        }
    })
}

/// The RediSearch index dump of `cache.Redis.Init`: `FT.INFO documents`, written
/// as the Go tool writes it under RESP2.
pub async fn redis_ft_info(url: &str) -> Result<String> {
    let client = redis::Client::open(url).map_err(fail)?;
    let mut connection = redis::aio::ConnectionManager::new(client)
        .await
        .map_err(fail)?;
    let info: redis::Value = redis::cmd("FT.INFO")
        .arg("documents")
        .query_async(&mut connection)
        .await
        .map_err(fail)?;
    Ok(format!(
        "FT.INFO documents (RESP2, created by cache.Redis.Init)\n\n{}\n",
        go_format(&info)?
    ))
}

/// Go's `%v` of a RESP2 reply as go-redis returns it: an array is `[a b]`, a
/// string its text, an integer its decimal form and nil `<nil>`.
pub fn go_format(value: &redis::Value) -> Result<String> {
    Ok(match value {
        redis::Value::Nil => "<nil>".to_owned(),
        redis::Value::Int(n) => n.to_string(),
        redis::Value::BulkString(bytes) => String::from_utf8(bytes.clone()).map_err(fail)?,
        redis::Value::SimpleString(text) => text.clone(),
        redis::Value::Okay => "OK".to_owned(),
        redis::Value::Array(items) => format!(
            "[{}]",
            items
                .iter()
                .map(go_format)
                .collect::<Result<Vec<_>>>()?
                .join(" ")
        ),
        other => return Err(fail(format!("reply {other:?} has no RESP2 form"))),
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schema_pg_clean_drops_the_script_filters_and_squeezes_blank_lines() {
        let dump = "--\n-- PostgreSQL database dump\n-- Dumped from database version 10.0\n\nSET statement_timeout = 0;\n\nCREATE TABLE public.users (\n    id text\n);\n\n\n\nSELECT pg_catalog.set_config('x', 'y', false);\nCREATE EXTENSION IF NOT EXISTS btree_gin;\n-- Name: EXTENSION plpgsql\n--\n";
        assert_eq!(
            pg_clean(dump),
            "\nCREATE TABLE public.users (\n    id text\n);\n\nCREATE EXTENSION IF NOT EXISTS btree_gin;\n"
        );
    }

    #[test]
    fn schema_go_format_matches_fmt_v_of_resp2_replies() {
        let reply = redis::Value::Array(vec![
            redis::Value::BulkString(b"num_docs".to_vec()),
            redis::Value::Int(1),
            redis::Value::Array(vec![
                redis::Value::Nil,
                redis::Value::BulkString(b"x".to_vec()),
            ]),
            redis::Value::Array(vec![]),
        ]);
        assert_eq!(
            go_format(&reply).as_deref(),
            Ok("[num_docs 1 [<nil> x] []]")
        );
    }

    #[test]
    fn schema_bson_json_writes_go_values() {
        let document =
            doc! { "unique": true, "expireAfterSeconds": 3600, "weight": 1.0_f64, "keys": ["a"] };
        let value = bson_json(&Bson::Document(document)).expect("supported types");
        let text = gojson::marshal_indent(&value).expect("writable");
        assert_eq!(
            text,
            "{\n  \"expireAfterSeconds\": 3600,\n  \"keys\": [\n    \"a\"\n  ],\n  \"unique\": true,\n  \"weight\": 1\n}"
        );
    }

    #[test]
    fn schema_sqlite_dump_of_an_empty_database_is_the_header() {
        let dir = tempfile::tempdir().expect("temporary directory");
        let path = dir.path().join("empty.sqlite");
        rusqlite::Connection::open(&path).expect("create the database");
        assert_eq!(sqlite(&path).as_deref(), Ok(&format!("{GO_HEADER}\n")[..]));
    }
}

#!/usr/bin/env python3
"""Regenerates porting/dependency-graph.md from `go list` output.

Usage (from the repository root): python3 porting/tools/depgraph.py > porting/dependency-graph.md
Lines of code are counted the same way as the project plan: hand-written
non-test .go files (generated *.pb.go excluded) and *_test.go files separately.
"""
import json
import os
import subprocess
import sys

MODULE = "github.com/gorse-io/gorse/"
SKIP_PREFIXES = ("contracts/",)  # our own contract tools, not upstream code

out = subprocess.run(["go", "list", "-json", "./..."], check=True, capture_output=True, text=True).stdout
decoder = json.JSONDecoder()
pkgs, idx = [], 0
while idx < len(out):
    while idx < len(out) and out[idx].isspace():
        idx += 1
    if idx >= len(out):
        break
    obj, idx = decoder.raw_decode(out, idx)
    pkgs.append(obj)

def rel(p):
    return p[len(MODULE):] if p.startswith(MODULE) else p

def lines(directory, files):
    total = 0
    for f in files:
        with open(os.path.join(directory, f), encoding="utf-8") as fh:
            total += sum(1 for _ in fh)
    return total

info = {}
for p in pkgs:
    name = rel(p["ImportPath"])
    if name.startswith(SKIP_PREFIXES):
        continue
    src = [f for f in p.get("GoFiles", []) + p.get("CgoFiles", []) + p.get("IgnoredGoFiles", []) if not f.endswith(".pb.go") and not f.endswith("_test.go")]
    tests = p.get("TestGoFiles", []) + p.get("XTestGoFiles", [])
    deps = sorted({rel(d) for d in p.get("Imports", []) if d.startswith(MODULE)})
    info[name] = {"deps": deps, "src": lines(p["Dir"], src), "test": lines(p["Dir"], tests)}
for v in info.values():
    v["deps"] = [d for d in v["deps"] if d in info]

level = {}
def depth(n, stack=()):
    if n in level:
        return level[n]
    if n in stack:
        raise SystemExit(f"cycle at {n}")
    level[n] = 0 if not info[n]["deps"] else 1 + max(depth(d, stack + (n,)) for d in info[n]["deps"])
    return level[n]
for n in info:
    depth(n)

w = sys.stdout.write
w("<!-- Generated by porting/tools/depgraph.py from `go list` at the pinned commit. Do not edit. -->\n")
w("# Go package dependency graph\n\n")
w("Level 0 packages import no other Gorse package; a package at level N imports only packages at lower levels.\n")
w("`src` counts hand-written non-test lines (generated `*.pb.go` excluded, build-tagged variants included); `test` counts `*_test.go` lines.\n\n")
w("| Level | Package | src | test | Imports (Gorse packages) |\n|---|---|---|---|---|\n")
for n in sorted(info, key=lambda n: (level[n], n)):
    w(f"| {level[n]} | `{n}` | {info[n]['src']} | {info[n]['test']} | {', '.join('`'+d+'`' for d in info[n]['deps'])} |\n")
w(f"\nTotals: src {sum(v['src'] for v in info.values())}, test {sum(v['test'] for v in info.values())} lines across {len(info)} packages.\n\n")
w("```mermaid\ngraph BT\n")
for n in sorted(info):
    for d in info[n]["deps"]:
        w(f"  {n.replace('/', '_').replace('-', '_')}[{n}] --> {d.replace('/', '_').replace('-', '_')}[{d}]\n")
w("```\n")

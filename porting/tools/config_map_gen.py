#!/usr/bin/env python3
"""Generates crates/gorse-master/src/rest/config_map.rs.

Go's master serves `GET /api/dashboard/config` from `mapstructure.Decode(m.Config, &configMap)`:
every struct becomes a map keyed by its `mapstructure` tag. The field list of each struct is
the list of `f.decode("tag", &mut out.field, errs)` calls in its `Decode` impl in
crates/gorse-config/src/config/schema.rs, which mirrors the Go struct. This script reads those
calls and writes one encoder per struct, so the two cannot drift apart silently.

Usage: python3 porting/tools/config_map_gen.py   (from the repository root)
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "crates/gorse-config/src/config/schema.rs"
OUT = ROOT / "crates/gorse-master/src/rest/config_map.rs"

IMPL_RE = re.compile(r"impl Decode for (\w+) \{")
FIELD_RE = re.compile(r'f\.decode\(\s*"([^"]+)",\s*&mut out\.(\w+),\s*errs,?\s*\);', re.S)


def blocks(text):
    """Yields (struct name, decode body) for each `impl Decode for` block."""
    for match in IMPL_RE.finditer(text):
        start = match.end()
        depth = 1
        i = start
        while depth:
            if text[i] == "{":
                depth += 1
            elif text[i] == "}":
                depth -= 1
            i += 1
        yield match.group(1), text[start : i - 1]


FN_CALL_RE = re.compile(r"decode_struct\(\s*self,\s*name,\s*\"[^\"]*\",\s*input,\s*errs,\s*([a-z_0-9]+),?\s*\)", re.S)


def function_body(text, fn_name):
    """The body of the free function `fn_name` that a Decode impl hands to decode_struct."""
    match = re.search(rf"fn {fn_name}\([^)]*\)[^{{]*\{{", text)
    if not match:
        return ""
    start = match.end()
    depth = 1
    i = start
    while depth:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
        i += 1
    return text[start : i - 1]


def main():
    text = SCHEMA.read_text()
    structs = []
    for name, body in blocks(text):
        call = FN_CALL_RE.search(body)
        if call:
            body = function_body(text, call.group(1))
        fields = FIELD_RE.findall(body)
        if not fields:
            print(f"{name}: no decode calls found", file=sys.stderr)
            return 1
        structs.append((name, fields))
    names = {name for name, _ in structs}
    out = []
    out.append("// Ports: config/config.go (the mapstructure map of config.Config that master/rest.go's getConfig builds) @ add21b5")
    out.append("")
    out.append("//! The `mapstructure` map of the configuration, which `GET /api/dashboard/config` serves.")
    out.append("//!")
    out.append("//! Generated by `porting/tools/config_map_gen.py` from the `Decode` impls in")
    out.append("//! `crates/gorse-config/src/config/schema.rs`. Do not edit this file by hand: change the")
    out.append("//! generator or the schema, and run it again.")
    out.append("")
    out.append("use gorse_config::config::schema::*;")
    out.append("use serde_json::{Map, Value};")
    out.append("")
    out.append("use super::config::ToConfigValue;")
    out.append("")
    for name, fields in structs:
        out.append(f"/// The `mapstructure` map of a [`{name}`].")
        out.append(f"pub(crate) fn {snake(name)}_map(cfg: &{name}) -> Map<String, Value> {{")
        out.append("    let mut map = Map::new();")
        for tag, field in fields:
            out.append(f'    map.insert("{tag}".to_owned(), cfg.{field}.to_config_value());')
        out.append("    map")
        out.append("}")
        out.append("")
        out.append(f"impl ToConfigValue for {name} {{")
        out.append("    fn to_config_value(&self) -> Value {")
        out.append(f"        Value::Object({snake(name)}_map(self))")
        out.append("    }")
        out.append("}")
        out.append("")
    OUT.write_text("\n".join(out).rstrip() + "\n")
    print(f"wrote {len(structs)} encoders to {OUT.relative_to(ROOT)}")
    return 0


def snake(name):
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower().replace("o_i_d_c", "oidc")


if __name__ == "__main__":
    sys.exit(main())

// Command configschema regenerates the frozen configuration contract files in
// contracts/config/ from the Go config package:
//
//   - config.schema.json: the JSON Schema served by GET /api/dashboard/config/schema
//     (jsonschema.Reflector with FieldNameTag "mapstructure", as master.getConfigSchema does).
//   - meta-config.*.json: the JSON the master sends to workers and servers in
//     protocol.Meta.config (json.Marshal of config.Config, Go field names).
//   - config.keys.md: every TOML key with Go type, default, environment
//     variable and validation tag.
//
// Usage: go run ./contracts/tools/configschema -out contracts/config
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"strings"

	"github.com/gorse-io/gorse/config"
	"github.com/invopop/jsonschema"
)

// homePlaceholder replaces the machine-specific default data directory.
const homePlaceholder = "${HOME}/.gorse/var/lib"

func main() {
	out := flag.String("out", "contracts/config", "output directory")
	src := flag.String("src", "config", "directory of the Go config package (for config.toml and env bindings)")
	flag.Parse()
	tmp, err := os.MkdirTemp("", "gorse-config-")
	must(err)
	defer os.RemoveAll(tmp)
	config.RootDir = tmp

	defaults := config.GetDefaultConfig()

	// JSON Schema as served by the dashboard.
	reflector := jsonschema.Reflector{FieldNameTag: "mapstructure"}
	writeJSON(*out, "config.schema.json", reflector.Reflect(defaults), tmp)

	// Meta.config wire JSON, for the built-in defaults and for the sample config.toml.
	writeJSON(*out, "meta-config.default.json", defaults, tmp)
	sample, err := config.LoadConfig(filepath.Join(*src, "config.toml"))
	must(err)
	writeJSON(*out, "meta-config.sample.json", sample, tmp)

	// Key table.
	goSrc, err := os.ReadFile(filepath.Join(*src, "config.go"))
	must(err)
	envs := map[string]string{}
	for _, m := range regexp.MustCompile(`\{"([a-z0-9_.\-]+)", "([A-Z0-9_]+)"\}`).FindAllStringSubmatch(string(goSrc), -1) {
		envs[m[1]] = m[2]
	}
	var rows []string
	seen := map[string]bool{}
	walk(reflect.ValueOf(*defaults), "", func(key, typ, def, validate string) {
		seen[key] = true
		env := envs[key]
		rows = append(rows, fmt.Sprintf("| `%s` | %s | %s | %s | %s |", key, typ, def, code(env), code(validate)))
	})
	var orphans []string
	for key, env := range envs {
		if !seen[key] {
			orphans = append(orphans, fmt.Sprintf("- `%s` is bound to `%s` but no config field has this key (the binding has no effect).", key, env))
		}
	}
	md := fmt.Sprintf(`<!-- Generated by contracts/tools/configschema. Do not edit. -->
# Configuration keys (%d)

Keys are TOML paths (viper keys, from mapstructure tags). Defaults come from
config.GetDefaultConfig(); paths under the data directory are shown as %s.
Durations are written in TOML as Go duration strings ("10s", "72h") and travel
in Meta.config JSON as integer nanoseconds.

| Key | Go type | Default | Env var | Validation |
|---|---|---|---|---|
%s

## Env bindings without a field

%s
`, len(rows), "`"+homePlaceholder+"`", strings.Join(rows, "\n"), strings.Join(orphans, "\n"))
	must(os.WriteFile(filepath.Join(*out, "config.keys.md"), []byte(strings.ReplaceAll(md, tmp, homePlaceholder)), 0o644))

	toml, err := os.ReadFile(filepath.Join(*src, "config.toml"))
	must(err)
	must(os.WriteFile(filepath.Join(*out, "config.toml"), toml, 0o644))
}

func walk(v reflect.Value, prefix string, emit func(key, typ, def, validate string)) {
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		f := t.Field(i)
		name := strings.SplitN(f.Tag.Get("mapstructure"), ",", 2)[0]
		if name == "" || name == "-" {
			continue
		}
		key := name
		if prefix != "" {
			key = prefix + "." + name
		}
		fv := v.Field(i)
		if f.Type.Kind() == reflect.Struct && f.Type.String() != "time.Time" {
			walk(fv, key, emit)
			continue
		}
		def := fmt.Sprintf("%v", fv.Interface())
		if f.Type.Kind() == reflect.String {
			def = fmt.Sprintf("%q", fv.String())
		}
		if f.Type.Kind() == reflect.Slice && f.Type.Elem().Kind() == reflect.Struct && f.Type.Elem().String() != "expression.FeedbackTypeExpression" {
			def = fmt.Sprintf("[] (array of tables, %d entries)", fv.Len())
		}
		emit(key, "`"+f.Type.String()+"`", "`"+def+"`", f.Tag.Get("validate"))
	}
}

func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + s + "`"
}

func writeJSON(dir, name string, v any, tmp string) {
	buf, err := json.MarshalIndent(v, "", "  ")
	must(err)
	buf = []byte(strings.ReplaceAll(string(buf), tmp, homePlaceholder))
	must(os.WriteFile(filepath.Join(dir, name), append(buf, '\n'), 0o644))
	fmt.Println("wrote", filepath.Join(dir, name))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

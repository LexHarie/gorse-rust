// Command exprunicode writes the Unicode tables the gorse-expr crate needs to
// classify characters exactly as the Go toolchain that builds Gorse does:
//
//	go run ./contracts/tools/exprunicode -out crates/gorse-expr/src/unicode_tables.rs
//
// The expr-lang lexer splits identifiers with unicode.IsLetter and
// unicode.IsDigit and skips unicode.IsSpace, and its errors and the AST
// printer quote text with strconv.Quote, which escapes what strconv.IsPrint
// rejects. Rust's char methods implement other properties (Alphabetic,
// Numeric, White_Space), so the crate carries these sets as sorted, disjoint
// ranges of code points instead.
//
// Letters and digits are read from the Go range tables unicode.L and
// unicode.Nd; space and print have no exported table and are found by asking
// unicode.IsSpace and strconv.IsPrint about every code point. The golden
// tests (contracts/tools/exprparsegolden) check the Rust lookups against the
// Go functions themselves for every code point.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"runtime"
	"strconv"
	"unicode"
)

type span struct{ lo, hi rune }

// fromTable flattens a Go range table into inclusive spans, merging
// neighbours.
func fromTable(t *unicode.RangeTable) []span {
	var out []span
	add := func(lo, hi, stride rune) {
		for r := lo; r <= hi; r += stride {
			if n := len(out); n > 0 && out[n-1].hi+1 == r {
				out[n-1].hi = r
			} else {
				out = append(out, span{r, r})
			}
		}
	}
	for _, r := range t.R16 {
		add(rune(r.Lo), rune(r.Hi), rune(r.Stride))
	}
	for _, r := range t.R32 {
		add(rune(r.Lo), rune(r.Hi), rune(r.Stride))
	}
	return out
}

// fromFunc collects the code points a predicate accepts.
func fromFunc(f func(rune) bool) []span {
	var out []span
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !f(r) {
			continue
		}
		if n := len(out); n > 0 && out[n-1].hi+1 == r {
			out[n-1].hi = r
		} else {
			out = append(out, span{r, r})
		}
	}
	return out
}

func table(b *bytes.Buffer, name, doc string, spans []span) {
	fmt.Fprintf(b, "/// %s\n", doc)
	fmt.Fprintf(b, "pub(crate) static %s: &[(u32, u32)] = &[\n", name)
	for _, s := range spans {
		fmt.Fprintf(b, "    (0x%04x, 0x%04x),\n", s.lo, s.hi)
	}
	b.WriteString("];\n")
}

func main() {
	out := flag.String("out", "", "output Rust file")
	flag.Parse()
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by contracts/tools/exprunicode from the unicode and strconv\n")
	fmt.Fprintf(&b, "// packages of %s (Unicode %s). DO NOT EDIT.\n\n", runtime.Version(), unicode.Version)
	b.WriteString("//! Character sets of the Go toolchain that builds Gorse, as sorted, disjoint,\n")
	b.WriteString("//! inclusive ranges of code points.\n\n")
	table(&b, "LETTER", "`unicode.IsLetter`: general category L.", fromTable(unicode.L))
	b.WriteString("\n")
	table(&b, "DIGIT", "`unicode.IsDigit`: general category Nd.", fromTable(unicode.Nd))
	b.WriteString("\n")
	table(&b, "SPACE", "`unicode.IsSpace`: Latin-1 space characters and the White_Space property.", fromFunc(unicode.IsSpace))
	b.WriteString("\n")
	table(&b, "PRINT", "`strconv.IsPrint`: letters, marks, numbers, punctuation, symbols and U+0020.", fromFunc(strconv.IsPrint))
	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		panic(err)
	}
}

// Command openapi regenerates the frozen REST contract files in contracts/rest/.
//
// It builds the go-restful web services exactly as the Go server and master
// nodes do (server.RestServer.CreateWebService, master.Master.CreateWebService)
// and serialises the OpenAPI document that /apidocs.json would serve, plus a
// flat route table. No network listener or database is needed.
//
// Each node is generated in its own process (-node server|master) because
// go-restful-openapi derives operationIds of anonymous handlers from a
// process-wide counter; generating both in one process shifts them.
//
// Usage: go run ./contracts/tools/openapi -node server -out contracts/rest
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	restfulspec "github.com/emicklei/go-restful-openapi/v2"
	"github.com/emicklei/go-restful/v3"
	"github.com/gorse-io/gorse/config"
	"github.com/gorse-io/gorse/master"
	"github.com/gorse-io/gorse/server"
)

func main() {
	out := flag.String("out", "contracts/rest", "output directory")
	node := flag.String("node", "", "server or master")
	flag.Parse()
	tmp, err := os.MkdirTemp("", "gorse-openapi-")
	if err != nil {
		panic(err)
	}
	defer os.RemoveAll(tmp)
	config.RootDir = tmp

	switch *node {
	case "server":
		// Server node: only server routes.
		srv := &server.RestServer{Config: config.GetDefaultConfig(), WebService: new(restful.WebService)}
		srv.CreateWebService()
		write(*out, "server", srv.WebService)
	case "master":
		// Master node: dashboard routes registered first, then the server routes on
		// the same WebService (see master.StartHttpServer -> RestServer.StartHttpServer).
		m := &master.Master{}
		m.RestServer = server.RestServer{Config: config.GetDefaultConfig(), WebService: new(restful.WebService)}
		m.CreateWebService()
		m.RestServer.CreateWebService()
		write(*out, "master", m.WebService)
	default:
		panic("-node must be server or master")
	}
}

func write(dir, name string, ws *restful.WebService) {
	spec := restfulspec.BuildSwagger(restfulspec.Config{
		WebServices: []*restful.WebService{ws},
		APIPath:     "/apidocs.json",
	})
	buf, err := json.MarshalIndent(spec, "", "  ")
	if err != nil {
		panic(err)
	}
	must(os.WriteFile(filepath.Join(dir, name+".openapi.json"), append(buf, '\n'), 0o644))

	var lines []string
	for _, r := range ws.Routes() {
		var params []string
		for _, p := range r.ParameterDocs {
			d := p.Data()
			kind := map[int]string{restful.PathParameterKind: "path", restful.QueryParameterKind: "query",
				restful.BodyParameterKind: "body", restful.HeaderParameterKind: "header",
				restful.FormParameterKind: "form", restful.MultiPartFormParameterKind: "multipart"}[d.Kind]
			params = append(params, fmt.Sprintf("%s:%s(%s)", kind, d.Name, d.DataType))
		}
		reads := ""
		if r.ReadSample != nil {
			reads = fmt.Sprintf("%T", r.ReadSample)
		}
		writes := ""
		if r.WriteSample != nil {
			writes = fmt.Sprintf("%T", r.WriteSample)
		}
		lines = append(lines, fmt.Sprintf("| %s | `%s` | %s | %s | %s |",
			r.Method, r.Path, strings.Join(params, " "), reads, writes))
	}
	sort.Strings(lines)
	header := "| Method | Path | Parameters | Reads (Go type) | Writes (Go type) |\n|---|---|---|---|---|\n"
	must(os.WriteFile(filepath.Join(dir, name+".routes.md"),
		[]byte(fmt.Sprintf("<!-- Generated by contracts/tools/openapi. Do not edit. -->\n# %s go-restful routes (%d)\n\n%s%s\n",
			name, len(lines), header, strings.Join(lines, "\n"))), 0o644))
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

// floatInputs is every ParseFloat input: the hand-picked edge cases first,
// then the seeded corpus.
func floatInputs() []string {
	in := append([]string(nil), handFloats()...)
	r := rand.New(rand.NewSource(20261019))
	for range 1500 {
		in = append(in, randDecimal(r))
	}
	for range 1000 {
		in = append(in, fromBits64(r))
	}
	for range 500 {
		in = append(in, fromBits32(r))
	}
	for range 300 {
		in = append(in, halfway64(r)...)
	}
	for range 150 {
		in = append(in, halfway32(r)...)
	}
	for range 400 {
		in = append(in, longMantissa(r))
	}
	for range 800 {
		in = append(in, randHex(r))
	}
	for range 400 {
		in = append(in, withUnderscores(r))
	}
	for range 200 {
		in = append(in, randSpecial(r))
	}
	for range 300 {
		in = append(in, withSuffix(r))
	}
	for range 500 {
		in = append(in, garbage(r))
	}
	return in
}


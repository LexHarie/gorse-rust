func main() {
	pow10tab := flag.String("pow10tab", "", "write the pow10Tab table (Rust) here")
	out := flag.String("out", "", "write the strconv golden JSON here")
	flag.Parse()

	if *pow10tab != "" {
		src, err := pow10Table()
		must(err)
		must(os.WriteFile(*pow10tab, []byte(src), 0o644))
	}
	if *out != "" {
		must(writeJSON(*out, golden()))
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}

func must(err error) {
	if err != nil {
		fail(err)
	}
}

var (
	pow10Const = regexp.MustCompile(`(?m)^\tpow10(Min|Max) = (-?\d+)$`)
	pow10Entry = regexp.MustCompile(`^\t\{(0x[0-9a-f]{16}), (0x[0-9a-f]{16})\}, // (1e-?\d+ \* 2\*\*-?\d+)$`)
)

// pow10Table converts pow10tab.go to Rust: the constants, the doc comment and
// every {hi, lo} entry with its comment, in order.
func pow10Table() (string, error) {
	path := filepath.Join(runtime.GOROOT(), "src", "internal", "strconv", "pow10tab.go")
	data, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	src := string(data)
	consts := map[string]string{}
	for _, m := range pow10Const.FindAllStringSubmatch(src, -1) {
		consts[m[1]] = m[2]
	}
	if consts["Min"] == "" || consts["Max"] == "" {
		return "", fmt.Errorf("%s: pow10Min or pow10Max not found", path)
	}
	const docStart = "// pow10Tab holds"
	start := strings.Index(src, docStart)
	if start < 0 {
		return "", fmt.Errorf("%s: pow10Tab doc comment not found", path)
	}
	var doc []string
	var entries []string
	inTable := false
	for _, line := range strings.Split(src[start:], "\n") {
		switch {
		case !inTable && strings.HasPrefix(line, "//"):
			doc = append(doc, "///"+strings.TrimPrefix(line, "//"))
		case !inTable && line == "var pow10Tab = [...]pmHiLo{":
			inTable = true
		case inTable && line == "}":
			inTable = false
		case inTable:
			m := pow10Entry.FindStringSubmatch(line)
			if m == nil {
				return "", fmt.Errorf("%s: unexpected table line %q", path, line)
			}
			entries = append(entries, fmt.Sprintf("    (%s, %s), // %s\n", m[1], m[2], m[3]))
		}
		if !inTable && len(entries) > 0 {
			break
		}
	}
	min, err := strconv.Atoi(consts["Min"])
	if err != nil {
		return "", err
	}
	max, err := strconv.Atoi(consts["Max"])
	if err != nil {
		return "", err
	}
	if len(entries) != max-min+1 {
		return "", fmt.Errorf("%s: %d entries, want %d", path, len(entries), max-min+1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by contracts/tools/strconvgolden -pow10tab; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Ports: $GOROOT/src/internal/strconv/pow10tab.go @ %s\n", runtime.Version())
	b.WriteString("//\n")
	b.WriteString("// Derived from Go's strconv package: Copyright 2025 The Go Authors. All\n")
	b.WriteString("// rights reserved. Use of this source code is governed by a BSD-style license\n")
	b.WriteString("// that can be found in crates/gorse-common/licenses/GO-LICENSE.\n\n")
	b.WriteString("//! Go's `pow10Tab`: the 128-bit mantissas of the powers of 10 that\n")
	b.WriteString("//! `uscale` multiplies by, copied entry for entry.\n\n")
	b.WriteString("/// Go's `pow10Min`.\n")
	fmt.Fprintf(&b, "pub(super) const POW10_MIN: i64 = %d;\n", min)
	b.WriteString("/// Go's `pow10Max`.\n")
	fmt.Fprintf(&b, "pub(super) const POW10_MAX: i64 = %d;\n\n", max)
	for _, line := range doc {
		b.WriteString(line + "\n")
	}
	b.WriteString("/// Each entry is Go's `pmHiLo{hi, lo}`, which represents hi<<64 - lo.\n")
	b.WriteString("pub(super) static POW10_TAB: [(u64, u64); (POW10_MAX - POW10_MIN + 1) as usize] = [\n")
	for _, e := range entries {
		b.WriteString(e)
	}
	b.WriteString("];\n")
	return b.String(), nil
}

// Golden is the content of strconv_golden.json.
type Golden struct {
	GoVersion  string        `json:"go_version"`
	ParseFloat []FloatCase   `json:"parse_float"`
	BitSize    []BitSizeCase `json:"bit_size"`
	Format     []FormatCase  `json:"format"`
	ParseBool  []BoolCase    `json:"parse_bool"`
}

// FloatCase is ParseFloat(in, 32) and ParseFloat(in, 64). An input that is
// not valid UTF-8 is in InHex instead of In (JSON strings hold only UTF-8).
// Bits are the float64 bits ParseFloat returns, as 16 hex digits; Err is
// "", "syntax" or "range"; Text is err.Error(); G is FormatFloat of the
// result with 'g', -1 and the bit size.
type FloatCase struct {
	In     string `json:"in"`
	InHex  string `json:"in_hex,omitempty"`
	Bits64 string `json:"bits64"`
	Err64  string `json:"err64"`
	Text64 string `json:"text64"`
	G64    string `json:"g64"`
	Bits32 string `json:"bits32"`
	Err32  string `json:"err32"`
	Text32 string `json:"text32"`
	G32    string `json:"g32"`
}

// BitSizeCase is ParseFloat(in, bitSize) for a bit size other than 32 and 64.
type BitSizeCase struct {
	In      string `json:"in"`
	BitSize int    `json:"bit_size"`
	Bits    string `json:"bits"`
	Err     string `json:"err"`
	Text    string `json:"text"`
}

// FormatCase is FormatFloat of a float64 (Size 64) or a float32 (Size 32,
// Bits holding its float32 bits): 'g' and 'b' with precision -1, and 'e'
// with each precision from 0 to len(E)-1.
type FormatCase struct {
	Size int      `json:"size"`
	Bits string   `json:"bits"`
	G    string   `json:"g"`
	B    string   `json:"b"`
	E    []string `json:"e"`
}

// BoolCase is ParseBool(in).
type BoolCase struct {
	In    string `json:"in"`
	InHex string `json:"in_hex,omitempty"`
	Out   bool   `json:"out"`
	Err   string `json:"err"`
	Text  string `json:"text"`
}

func golden() Golden {
	g := Golden{GoVersion: runtime.Version()}
	for _, s := range floatInputs() {
		g.ParseFloat = append(g.ParseFloat, floatCase(s))
	}
	for _, s := range bitSizeInputs {
		for _, bitSize := range []int{-1, 0, 1, 8, 16, 31, 33, 63, 65, 100, 128} {
			f, err := strconv.ParseFloat(s, bitSize)
			kind, text := errInfo(err)
			g.BitSize = append(g.BitSize, BitSizeCase{
				In:      s,
				BitSize: bitSize,
				Bits:    fmt.Sprintf("%016x", math.Float64bits(f)),
				Err:     kind,
				Text:    text,
			})
		}
	}
	g.Format = formatCases()
	for _, s := range boolInputs() {
		b, err := strconv.ParseBool(s)
		kind, text := errInfo(err)
		in, inHex := splitInput(s)
		g.ParseBool = append(g.ParseBool, BoolCase{In: in, InHex: inHex, Out: b, Err: kind, Text: text})
	}
	return g
}

func floatCase(s string) FloatCase {
	f64, err64 := strconv.ParseFloat(s, 64)
	f32, err32 := strconv.ParseFloat(s, 32)
	kind64, text64 := errInfo(err64)
	kind32, text32 := errInfo(err32)
	in, inHex := splitInput(s)
	return FloatCase{
		In:     in,
		InHex:  inHex,
		Bits64: fmt.Sprintf("%016x", math.Float64bits(f64)),
		Err64:  kind64,
		Text64: text64,
		G64:    strconv.FormatFloat(f64, 'g', -1, 64),
		Bits32: fmt.Sprintf("%016x", math.Float64bits(f32)),
		Err32:  kind32,
		Text32: text32,
		G32:    strconv.FormatFloat(f32, 'g', -1, 32),
	}
}

func splitInput(s string) (in, inHex string) {
	if utf8.ValidString(s) {
		return s, ""
	}
	return "", hex.EncodeToString([]byte(s))
}

func errInfo(err error) (kind, text string) {
	switch {
	case err == nil:
		return "", ""
	case errors.Is(err, strconv.ErrSyntax):
		return "syntax", err.Error()
	case errors.Is(err, strconv.ErrRange):
		return "range", err.Error()
	}
	fail(fmt.Errorf("unexpected error %v", err))
	return "", ""
}


func digits(r *rand.Rand, n int) string {
	b := make([]byte, n)
	for i := range b {
		b[i] = byte('0' + r.Intn(10))
	}
	return string(b)
}

func sign(r *rand.Rand) string {
	switch r.Intn(4) {
	case 0:
		return "-"
	case 1:
		return "+"
	}
	return ""
}

// exponent is an optional exponent of the given letter, mostly small but
// sometimes near the float range edges or huge.
func exponent(r *rand.Rand, letter string) string {
	var e int
	switch r.Intn(6) {
	case 0:
		return ""
	case 1, 2:
		e = r.Intn(30)
	case 3:
		e = 280 + r.Intn(80)
	case 4:
		e = r.Intn(400)
	case 5:
		e = r.Intn(200000)
	}
	es := strconv.Itoa(e)
	if r.Intn(8) == 0 {
		es = strings.Repeat("0", r.Intn(5)) + es
	}
	if r.Intn(2) == 0 {
		letter = strings.ToUpper(letter)
	}
	return letter + sign(r) + es
}

// randDecimal is a decimal mantissa of up to 25 digits with an optional point
// and exponent.
func randDecimal(r *rand.Rand) string {
	intDigits := r.Intn(21)
	fracDigits := r.Intn(21)
	m := digits(r, intDigits)
	if r.Intn(3) > 0 {
		m += "." + digits(r, fracDigits)
	}
	if r.Intn(10) == 0 {
		m = strings.Repeat("0", r.Intn(30)) + m
	}
	return sign(r) + m + exponent(r, "e")
}

// fromBits64 formats random float64 bits the ways Go's tests do.
func fromBits64(r *rand.Rand) string {
	f := math.Float64frombits(r.Uint64())
	if math.IsNaN(f) || math.IsInf(f, 0) {
		f = math.Float64frombits(r.Uint64() >> 2)
	}
	switch r.Intn(4) {
	case 0:
		return strconv.FormatFloat(f, 'e', r.Intn(25), 64)
	case 1:
		return strconv.FormatFloat(f, 'g', 15+r.Intn(5), 64)
	case 2:
		if math.Abs(f) < 1e30 && math.Abs(f) > 1e-30 {
			return strconv.FormatFloat(f, 'f', -1, 64)
		}
	}
	return strconv.FormatFloat(f, 'g', -1, 64)
}

// fromBits32 formats random float32 bits.
func fromBits32(r *rand.Rand) string {
	f := math.Float32frombits(r.Uint32())
	if math.IsNaN(float64(f)) || math.IsInf(float64(f), 0) {
		f = math.Float32frombits(r.Uint32() >> 2)
	}
	switch r.Intn(3) {
	case 0:
		return strconv.FormatFloat(float64(f), 'e', 6+r.Intn(6), 32)
	case 1:
		return strconv.FormatFloat(float64(f), 'g', 20, 32)
	}
	return strconv.FormatFloat(float64(f), 'g', -1, 32)
}

// exactDecimal is the exact decimal expansion of x in 'e' form.
func exactDecimal(x *big.Float) string {
	s := x.Text('e', 1200)
	mant, exp, _ := strings.Cut(s, "e")
	mant = strings.TrimRight(mant, "0")
	mant = strings.TrimSuffix(mant, ".")
	return mant + "e" + exp
}

// nudge returns the halfway point s and decimals just above and below it.
func nudge(s string) []string {
	mant, exp, _ := strings.Cut(s, "e")
	above := mant
	if !strings.Contains(above, ".") {
		above += "."
	}
	above += strings.Repeat("0", 3) + "1"
	below := mant[:len(mant)-1] + string(mant[len(mant)-1]-1) + "999"
	if !strings.Contains(mant, ".") {
		below = mant[:len(mant)-1] + string(mant[len(mant)-1]-1) + ".999"
	}
	return []string{s, above + "e" + exp, below + "e" + exp}
}

// halfway64 is the exact halfway point between a random float64 and the next
// one up, with decimals just above and below it.
func halfway64(r *rand.Rand) []string {
	var f float64
	for {
		f = math.Float64frombits(r.Uint64() &^ (1 << 63))
		if r.Intn(4) == 0 {
			f = math.Float64frombits(r.Uint64() >> 12) // subnormal
		}
		if !math.IsNaN(f) && !math.IsInf(f, 0) && f != math.MaxFloat64 {
			break
		}
	}
	next := math.Nextafter(f, math.Inf(1))
	mid := new(big.Float).SetPrec(2000).SetFloat64(f)
	mid.Add(mid, new(big.Float).SetFloat64(next))
	mid.Quo(mid, big.NewFloat(2))
	return nudge(exactDecimal(mid))
}

// halfway32 is halfway64 for float32.
func halfway32(r *rand.Rand) []string {
	var f float32
	for {
		f = math.Float32frombits(r.Uint32() &^ (1 << 31))
		if r.Intn(4) == 0 {
			f = math.Float32frombits(r.Uint32() >> 9) // subnormal
		}
		if !math.IsNaN(float64(f)) && !math.IsInf(float64(f), 0) && f != math.MaxFloat32 {
			break
		}
	}
	next := math.Nextafter32(f, float32(math.Inf(1)))
	mid := new(big.Float).SetPrec(2000).SetFloat64(float64(f))
	mid.Add(mid, new(big.Float).SetFloat64(float64(next)))
	mid.Quo(mid, big.NewFloat(2))
	return nudge(exactDecimal(mid))
}

// longMantissa has more than 800 significant digits, so decimal.set
// truncates it, with and without a point, sometimes with a nonzero digit
// past the cap, and an exponent that brings the value near the float range.
func longMantissa(r *rand.Rand) string {
	lead := digits(r, 1+r.Intn(20))
	if lead[0] == '0' {
		lead = "1" + lead[1:]
	}
	n := 760 + r.Intn(260)
	var body string
	switch r.Intn(3) {
	case 0:
		body = strings.Repeat("0", n)
	case 1:
		body = digits(r, n)
	default:
		body = strings.Repeat("9", n)
	}
	tail := ""
	if r.Intn(3) > 0 {
		tail = string(byte('1' + r.Intn(9)))
	}
	m := lead + body + tail
	total := len(m)
	if r.Intn(3) == 0 {
		at := 1 + r.Intn(total-1)
		m = m[:at] + "." + m[at:]
		total = at
	}
	if r.Intn(5) == 0 {
		m = "0." + strings.Repeat("0", r.Intn(400)) + strings.ReplaceAll(m, ".", "")
		total = 0
	}
	var e int
	switch r.Intn(4) {
	case 0:
		e = -(total - len(lead))
	case 1:
		e = -(total - len(lead)) + r.Intn(41) - 20
	case 2:
		e = -total + r.Intn(700) - 350
	default:
		return sign(r) + m
	}
	return sign(r) + m + "e" + strconv.Itoa(e)
}

func hexDigits(r *rand.Rand, n int) string {
	const hexChars = "0123456789abcdefABCDEF"
	b := make([]byte, n)
	for i := range b {
		b[i] = hexChars[r.Intn(len(hexChars))]
	}
	return string(b)
}

// randHex is a hex float, mostly well-formed.
func randHex(r *rand.Rand) string {
	prefix := "0x"
	if r.Intn(4) == 0 {
		prefix = "0X"
	}
	m := hexDigits(r, r.Intn(22))
	if r.Intn(2) == 0 {
		m += "." + hexDigits(r, r.Intn(22))
	}
	var e int
	switch r.Intn(4) {
	case 0:
		e = r.Intn(64)
	case 1:
		e = 960 + r.Intn(160)
	case 2:
		e = r.Intn(2400)
	case 3:
		e = 100 + r.Intn(120)
	}
	p := "p"
	if r.Intn(4) == 0 {
		p = "P"
	}
	exp := p + sign(r) + strconv.Itoa(e)
	if r.Intn(20) == 0 {
		exp = ""
	}
	return sign(r) + prefix + m + exp
}

// withUnderscores puts underscores into a decimal or hex float, sometimes
// where Go allows them and sometimes not.
func withUnderscores(r *rand.Rand) string {
	var s string
	if r.Intn(2) == 0 {
		s = randDecimal(r)
	} else {
		s = randHex(r)
	}
	for range 1 + r.Intn(3) {
		at := r.Intn(len(s) + 1)
		s = s[:at] + "_" + s[at:]
	}
	return s
}

// randSpecial is a prefix of "infinity" or "nan" in random case and sign.
func randSpecial(r *rand.Rand) string {
	word := "infinity"
	if r.Intn(3) == 0 {
		word = "nan"
	}
	word = word[:r.Intn(len(word)+1)]
	if r.Intn(3) == 0 {
		word += word
	}
	b := []byte(word)
	for i := range b {
		if r.Intn(2) == 0 {
			b[i] -= 'a' - 'A'
		}
	}
	return sign(r) + string(b)
}

// withSuffix is a valid float with bytes after it.
func withSuffix(r *rand.Rand) string {
	suffixes := []string{" ", "x", "e", "p", ".", "_", "i", "n", "0x1", "\x00", "\xff", "+1", "f"}
	var s string
	switch r.Intn(4) {
	case 0:
		s = randDecimal(r)
	case 1:
		s = randHex(r)
	case 2:
		s = randSpecial(r)
	default:
		s = fromBits64(r)
	}
	return s + suffixes[r.Intn(len(suffixes))]
}

// garbage is a short string over the bytes a float can contain and a few it
// cannot.
func garbage(r *rand.Rand) string {
	const alphabet = "0123456789.eEpPxX+-_iInNfFaAtTyY \x00\xff\xc3"
	b := make([]byte, r.Intn(14))
	for i := range b {
		b[i] = alphabet[r.Intn(len(alphabet))]
	}
	return string(b)
}

// formatCases are float64 and float32 values to format: zeros, extremes,
// powers of two and ten, and random bits.
func formatCases() []FormatCase {
	var cases []FormatCase
	f64 := func(f float64) {
		c := FormatCase{
			Size: 64,
			Bits: fmt.Sprintf("%016x", math.Float64bits(f)),
			G:    strconv.FormatFloat(f, 'g', -1, 64),
			B:    strconv.FormatFloat(f, 'b', -1, 64),
		}
		for prec := range 22 {
			c.E = append(c.E, strconv.FormatFloat(f, 'e', prec, 64))
		}
		cases = append(cases, c)
	}
	f32 := func(f float32) {
		c := FormatCase{
			Size: 32,
			Bits: fmt.Sprintf("%08x", math.Float32bits(f)),
			G:    strconv.FormatFloat(float64(f), 'g', -1, 32),
			B:    strconv.FormatFloat(float64(f), 'b', -1, 32),
		}
		for prec := range 12 {
			c.E = append(c.E, strconv.FormatFloat(float64(f), 'e', prec, 32))
		}
		cases = append(cases, c)
	}
	for _, f := range []float64{
		0, math.Copysign(0, -1), 1, -1, 0.1, 1e21, 1e20, 1e-4, 1e-5, 123456, 1234567,
		math.MaxFloat64, math.SmallestNonzeroFloat64, 2.2250738585072014e-308,
		math.Inf(1), math.Inf(-1), math.NaN(), 5e-324, 1 << 53, 0.5, 9.5, 0.95,
	} {
		f64(f)
	}
	for _, f := range []float32{
		0, float32(math.Copysign(0, -1)), 1, -1, 0.1, 1e21, 1e-4, 1e-5,
		math.MaxFloat32, math.SmallestNonzeroFloat32, 1.1754944e-38,
		float32(math.Inf(1)), float32(math.Inf(-1)), float32(math.NaN()), 1 << 24, 0.5, 9.5,
	} {
		f32(f)
	}
	r := rand.New(rand.NewSource(1019))
	for range 300 {
		f := math.Float64frombits(r.Uint64())
		if r.Intn(5) == 0 {
			f = math.Float64frombits(r.Uint64() >> 12)
		}
		f64(f)
	}
	for range 300 {
		f := math.Float32frombits(r.Uint32())
		if r.Intn(5) == 0 {
			f = math.Float32frombits(r.Uint32() >> 9)
		}
		f32(f)
	}
	return cases
}


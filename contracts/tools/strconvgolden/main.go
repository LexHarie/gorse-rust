// writeJSON writes v, a struct, as a JSON object with one line per scalar
// field and one line per element of each slice field, so that a regenerated
// golden diffs line by line.
func writeJSON(path string, v any) error {
	compact := func(x any) (string, error) {
		var buf bytes.Buffer
		enc := json.NewEncoder(&buf)
		enc.SetEscapeHTML(false)
		if err := enc.Encode(x); err != nil {
			return "", err
		}
		return strings.TrimSuffix(buf.String(), "\n"), nil
	}
	var b strings.Builder
	b.WriteString("{\n")
	rv := reflect.ValueOf(v)
	rt := rv.Type()
	for i := 0; i < rt.NumField(); i++ {
		name, _, _ := strings.Cut(rt.Field(i).Tag.Get("json"), ",")
		fmt.Fprintf(&b, "%q: ", name)
		f := rv.Field(i)
		if f.Kind() == reflect.Slice && f.Type().Elem().Kind() == reflect.Struct {
			b.WriteString("[\n")
			for j := 0; j < f.Len(); j++ {
				line, err := compact(f.Index(j).Interface())
				if err != nil {
					return err
				}
				b.WriteString(line)
				if j+1 < f.Len() {
					b.WriteString(",")
				}
				b.WriteString("\n")
			}
			b.WriteString("]")
		} else {
			line, err := compact(f.Interface())
			if err != nil {
				return err
			}
			b.WriteString(line)
		}
		if i+1 < rt.NumField() {
			b.WriteString(",")
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

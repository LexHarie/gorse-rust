// Command strconvgolden writes what Go's strconv.ParseFloat and ParseBool do,
// for the Rust port of both (WP-1-14, crates/gorse-common/src/gostrconv):
//
//   - -pow10tab: Rust source with pow10Tab, copied entry for entry from this
//     toolchain's $GOROOT/src/internal/strconv/pow10tab.go.
//   - -out: ParseFloat at bit sizes 32 and 64 over hand-picked edge cases and
//     a seeded corpus (decimal, hex, underscores, inf/nan, mantissas of more
//     than 800 digits, exact halfway points between floats, huge and tiny
//     exponents, garbage), with the float bits, the error and its text;
//     ParseFloat at other bit sizes; FormatFloat of float bits in the forms
//     the Rust ports of Go's tests format with ('g', 'b' and 'e'); and
//     ParseBool over its spellings and garbage (strconv_golden.json).
//
// The corpus comes from math/rand with fixed seeds, so the output is the same
// on every run.
//
// Regenerate (from the repository root):
//
//	go run ./contracts/tools/strconvgolden \
//	  -pow10tab crates/gorse-common/src/gostrconv/pow10tab.rs \
//	  -out crates/gorse-common/tests/data/strconv_golden.json

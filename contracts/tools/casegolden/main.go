// Command casegolden writes Go's simple case mappings for the Rust port
// (crates/gorse-common/src/gounicode), which viper and mapstructure match
// configuration keys with:
//
//   - -tables: Rust source with unicode.ToLower and unicode.SimpleFold,
//     enumerated over every code point (surrogates excluded: Go's UTF-8
//     decoder never yields one, and a Rust char cannot hold one);
//   - -out: strings.ToLower and strings.EqualFold over generated strings
//     (casegolden.json), which check the string functions built on them.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"runtime"
	"strings"
	"unicode"
)

// rng is splitmix64.
type rng struct{ state uint64 }

func (r *rng) next() uint64 {
	r.state += 0x9e3779b97f4a7c15
	z := r.state
	z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
	z = (z ^ (z >> 27)) * 0x94d049bb133111eb
	return z ^ (z >> 31)
}

func runes(keep func(rune) (rune, bool)) [][2]rune {
	var out [][2]rune
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		if m, ok := keep(r); ok {
			out = append(out, [2]rune{r, m})
		}
	}
	return out
}

func writeTables(path string) error {
	lower := runes(func(r rune) (rune, bool) { m := unicode.ToLower(r); return m, m != r })
	fold := runes(func(r rune) (rune, bool) { m := unicode.SimpleFold(r); return m, m != r })
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by contracts/tools/casegolden -tables; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "// Ports: unicode.ToLower and unicode.SimpleFold @ %s (Unicode %s)\n\n", runtime.Version(), unicode.Version)
	fmt.Fprintf(&b, "//! Go's simple case mappings, enumerated over every code point. Sorted by\n")
	fmt.Fprintf(&b, "//! code point; a code point not listed maps to itself.\n\n")
	for _, t := range []struct {
		name, doc string
		pairs     [][2]rune
	}{
		{"LOWER", "Code points whose `unicode.ToLower` differs, and what it is.", lower},
		{"FOLD", "Code points whose `unicode.SimpleFold` differs, and what it is: the\n/// next code point of its case orbit.", fold},
	} {
		fmt.Fprintf(&b, "/// %s\npub(super) static %s: &[(u32, u32)] = &[\n", t.doc, t.name)
		for _, p := range t.pairs {
			fmt.Fprintf(&b, "    (0x%x, 0x%x),\n", p[0], p[1])
		}
		fmt.Fprintf(&b, "];\n")
		if t.name == "LOWER" {
			b.WriteString("\n")
		}
	}
	return os.WriteFile(path, []byte(b.String()), 0o644)
}

// Golden is casegolden.json.
type Golden struct {
	// ToLower holds [s, strings.ToLower(s)].
	ToLower [][2]string `json:"to_lower"`
	// EqualFold holds [s, t] pairs that strings.EqualFold accepts, then
	// pairs it rejects.
	EqualFold    [][2]string `json:"equal_fold"`
	NotEqualFold [][2]string `json:"not_equal_fold"`
}

func writeGolden(path string) error {
	cased := runes(func(r rune) (rune, bool) {
		return r, unicode.SimpleFold(r) != r || unicode.ToLower(r) != r
	})
	pool := make([]rune, 0, len(cased)+64)
	for _, p := range cased {
		pool = append(pool, p[0])
	}
	pool = append(pool, []rune("azAZ09_.- éßİıſKÅẞΣςσ\U0010FFFF\u0080")...)
	r := &rng{state: 19}
	str := func(n int) []rune {
		s := make([]rune, n)
		for i := range s {
			if r.next()%3 == 0 {
				s[i] = rune('a' + r.next()%26)
			} else {
				s[i] = pool[r.next()%uint64(len(pool))]
			}
		}
		return s
	}
	var g Golden
	for i := 0; i < 1000; i++ {
		s := string(str(1 + int(r.next()%12)))
		g.ToLower = append(g.ToLower, [2]string{s, strings.ToLower(s)})
	}
	// Every code point with a case, alone.
	for _, c := range pool {
		g.ToLower = append(g.ToLower, [2]string{string(c), strings.ToLower(string(c))})
	}
	for i := 0; i < 3000; i++ {
		s := str(1 + int(r.next()%10))
		t := make([]rune, len(s))
		for j, c := range s {
			// Move each rune a few steps along its case orbit.
			for k := r.next() % 4; k > 0; k-- {
				c = unicode.SimpleFold(c)
			}
			t[j] = c
		}
		switch r.next() % 4 {
		case 0:
			// Change one rune to another.
			t[r.next()%uint64(len(t))] = pool[r.next()%uint64(len(pool))]
		case 1:
			// Drop or add a rune.
			if len(t) > 1 && r.next()%2 == 0 {
				t = t[:len(t)-1]
			} else {
				t = append(t, 'x')
			}
		}
		pair := [2]string{string(s), string(t)}
		if strings.EqualFold(pair[0], pair[1]) {
			g.EqualFold = append(g.EqualFold, pair)
		} else {
			g.NotEqualFold = append(g.NotEqualFold, pair)
		}
	}
	data, err := json.Marshal(g)
	if err != nil {
		return err
	}
	return os.WriteFile(path, append(data, '\n'), 0o644)
}

func main() {
	tables := flag.String("tables", "", "Rust tables to write")
	out := flag.String("out", "", "golden JSON to write")
	flag.Parse()
	if *tables == "" && *out == "" {
		fmt.Fprintln(os.Stderr, "casegolden: -tables or -out is required")
		os.Exit(2)
	}
	if *tables != "" {
		if err := writeTables(*tables); err != nil {
			fmt.Fprintln(os.Stderr, "casegolden:", err)
			os.Exit(1)
		}
	}
	if *out != "" {
		if err := writeGolden(*out); err != nil {
			fmt.Fprintln(os.Stderr, "casegolden:", err)
			os.Exit(1)
		}
	}
}

#!/usr/bin/env bash
# Regenerates contracts/schema/ from the Go implementation.
#
# Prerequisite: the backends from storage/docker-compose.yml are running
# (docker compose -f storage/docker-compose.yml up -d redis mysql postgres mongo).
# Run from the repository root.
set -euo pipefail

OUT=contracts/schema
POSTGRES_CONTAINER=${POSTGRES_CONTAINER:-storage-postgres-1}

go run ./contracts/tools/schemadump -out "$OUT" \
  -mysql 'root:password@tcp(127.0.0.1:3306)/' \
  -postgres 'postgres://gorse:gorse_pass@127.0.0.1:5432/' \
  -mongo 'mongodb://root:password@127.0.0.1:27017/' \
  -redis 'redis://127.0.0.1:6379/'

pg_dump_clean() {
  {
    echo "-- Generated by contracts/tools/dump-schemas.sh (pg_dump -s) from the Go implementation. Do not edit."
    echo "-- Server: $(docker exec "$POSTGRES_CONTAINER" postgres --version)"
    docker exec "$POSTGRES_CONTAINER" pg_dump -s --no-owner --no-privileges -U gorse "$1" |
      grep -v -e '^SET ' -e '^SELECT pg_catalog' -e '^--$' -e '^-- Dumped' -e '^-- PostgreSQL database dump' \
        -e 'plpgsql' -e '^-- Name: EXTENSION' |
      cat -s
  } > "$2"
  echo "wrote $2"
}
pg_dump_clean gorse_schema_data "$OUT/data/postgres.sql"
pg_dump_clean gorse_schema_data_search "$OUT/data/postgres.search.sql"
pg_dump_clean gorse_schema_cache "$OUT/cache/postgres.sql"

/// Go's `parseTime`, with its deferred retry: when the parser it returns has
/// an ambiguous date that fails with "month out of range", the input is
/// parsed again in `time.Local` with the other month/day preference. The
/// retry replaces the parser (a nil one included) and leaves the error.
fn parse_time(datestr: &[u8], loc: Option<&Location>, opts: &[ParserOption]) -> Outcome {
    let mut datestr = datestr.to_vec();
    let p = Parser::new(&datestr, loc, opts);
    if !p.retry_ambiguous_date_with_swap {
        return parse_time_body(p, &mut datestr, loc, opts);
    }
    // month out of range signifies that a day/month swap is the correct solution to an ambiguous date
    // this is because it means that a day is being interpreted as a month and overflowing the valid value for that
    // by retrying in this case, we can fix a common situation with no assumptions
    let (mut p, err) = parse_time_body(p, &mut datestr, loc, opts);
    // The deferred function: it sees the parser being returned (it may come
    // from a restart without the options) and the body's final datestr.
    let swap = match p.as_mut() {
        Some(q) if q.ambiguous_md => match q.parse() {
            // if it errors out with the following error, swap before we
            // get out of this function to reduce scope it needs to be applied on
            Err(e) if e.to_string().contains("month out of range") => Some(!q.prefer_month_first),
            _ => None,
        },
        _ => None,
    };
    if let Some(prefer_month_first) = swap {
        let mut modified_opts = opts.to_vec();
        // create the option to reverse the preference
        modified_opts.push(ParserOption::PreferMonthFirst(prefer_month_first));
        // turn off the retry to avoid endless recursion
        modified_opts.push(ParserOption::RetryAmbiguousDateWithSwap(false));
        let local = gotime::local();
        p = parse_time(&datestr, Some(&local), &modified_opts).0;
    }
    (p, err)
}

/// The body of Go's `parseTime`. datestr is its local variable, which some
/// paths change and the deferred retry reads.
fn parse_time_body(
    mut p: Parser,
    datestr: &mut Vec<u8>,
    loc: Option<&Location>,
    opts: &[ParserOption],
) -> Outcome {
    let mut i: i64 = 0;

    // General strategy is to read rune by rune through the date looking for
    // certain hints of what type of date we are dealing with.
    // Hopefully we only need to read about 5 or 6 bytes before
    // we figure it out and then attempt a parse
    'iter_runes: while i < golen(datestr) {
        // Leaving this block is Go's `continue`: the loop's i++ still runs.
        'next: {
            let (r, bytes_consumed) = decode_rune(&datestr[ix(i)..]);
            let r = char::from_u32(r).unwrap_or(char::REPLACEMENT_CHARACTER);
            if bytes_consumed > 1 {
                i += bytes_consumed as i64 - 1;
            }

            match p.state_date {
                DateState::Start => {
                    if is_digit(r) {
                        p.state_date = DateState::Digit;
                    } else if is_letter(r) {
                        p.state_date = DateState::Alpha;
                    } else {
                        return (None, Some(unknown_err(datestr)));
                    }
                }
                DateState::Digit => {
                    match r {
                        '-' | '\u{2212}' => {
                            // 2006-01-02
                            // 2013-Feb-03
                            // 13-Feb-03
                            // 29-Jun-2016
                            if i == 4 {
                                p.state_date = DateState::YearDash;
                                p.yeari = 0;
                                p.yearlen = i;
                                p.moi = i + 1;
                                p.set(0, "2006");
                            } else {
                                p.state_date = DateState::DigitDash;
                            }
                        }
                        '/' => {
                            // 08/May/2005
                            // 03/31/2005
                            // 2014/02/24
                            p.state_date = DateState::DigitSlash;
                            if i == 4 {
                                // 2014/02/24  -  Year first /
                                p.yearlen = i; // since it was start of datestr, i=len
                                p.moi = i + 1;
                                p.set_year();
                                p.state_date = DateState::DigitYearSlash;
                            } else {
                                // Either Ambiguous dd/mm vs mm/dd  OR dd/month/yy
                                // 08/May/2005
                                // 03/31/2005
                                // 31/03/2005
                                // (Go tests the byte after the slash as a
                                // rune: 0xC3 is 'Ã', a letter.)
                                if i + 2 < golen(&p.datestr)
                                    && is_letter(char::from(datestr[ix(i + 1)]))
                                {
                                    // 08/May/2005
                                    p.state_date = DateState::DigitSlashAlpha;
                                    p.moi = i + 1;
                                    p.daylen = 2;
                                    p.dayi = 0;
                                    p.set_day();
                                    break 'next;
                                }
                                // Ambiguous dd/mm vs mm/dd the bane of date-parsing
                                // 03/31/2005
                                // 31/03/2005
                                p.ambiguous_md = true;
                                if p.prefer_month_first {
                                    if p.molen == 0 {
                                        // 03/31/2005
                                        p.molen = i;
                                        p.set_month();
                                        p.dayi = i + 1;
                                    }
                                } else if p.daylen == 0 {
                                    p.daylen = i;
                                    p.set_day();
                                    p.moi = i + 1;
                                }
                            }
                        }
                        ':' => {
                            // 03/31/2005
                            // 2014/02/24
                            p.state_date = DateState::DigitColon;
                            if i == 4 {
                                p.yearlen = i;
                                p.moi = i + 1;
                                p.set_year();
                            } else {
                                p.ambiguous_md = true;
                                if p.prefer_month_first && p.molen == 0 {
                                    p.molen = i;
                                    p.set_month();
                                    p.dayi = i + 1;
                                }
                            }
                        }
                        '.' => {
                            // 3.31.2014
                            // 08.21.71
                            // 2014.05
                            p.state_date = DateState::DigitDot;
                            if i == 4 {
                                p.yearlen = i;
                                p.moi = i + 1;
                                p.set_year();
                            } else {
                                p.ambiguous_md = true;
                                p.moi = 0;
                                p.molen = i;
                                p.set_month();
                                p.dayi = i + 1;
                            }
                        }
                        ' ' => {
                            // 18 January 2018
                            // 8 January 2018
                            // 8 jan 2018
                            // 02 Jan 2018 23:59
                            // 02 Jan 2018 23:59:34
                            // 12 Feb 2006, 19:17
                            // 12 Feb 2006, 19:17:22
                            if i == 6 {
                                p.state_date = DateState::DigitSt;
                            } else {
                                p.state_date = DateState::DigitWs;
                                p.dayi = 0;
                                p.daylen = i;
                            }
                        }
                        '年' => {
                            // Chinese Year
                            p.state_date = DateState::DigitChineseYear;
                        }
                        ',' => return (None, Some(unknown_err(datestr))),
                        _ => break 'next,
                    }
                    p.part1_len = i;
                }
                DateState::DigitSt => {
                    p.set(0, "060102");
                    i -= 1;
                    p.state_time = TimeState::Start;
                    break 'iter_runes;
                }
                DateState::YearDash => {
                    // dateYearDashDashT
                    //  2006-01-02T15:04:05Z07:00
                    //  2020-08-17T17:00:00:000+0100
                    // dateYearDashDashWs
                    //  2013-04-01 22:43:22
                    // dateYearDashAlphaDash
                    //   2013-Feb-03
                    if r == '-' {
                        p.molen = i - p.moi;
                        p.dayi = i + 1;
                        p.state_date = DateState::YearDashDash;
                        p.set_month();
                    } else if is_letter(r) {
                        p.state_date = DateState::YearDashAlphaDash;
                    }
                }
                DateState::YearDashDash => {
                    // dateYearDashDashT
                    //  2006-01-02T15:04:05Z07:00
                    // dateYearDashDashWs
                    //  2013-04-01 22:43:22
                    // dateYearDashDashOffset
                    //  2020-07-20+00:00
                    match r {
                        '+' | '-' => {
                            p.offseti = i;
                            p.daylen = i - p.dayi;
                            p.state_date = DateState::YearDashDashOffset;
                            p.set_day();
                        }
                        ' ' => {
                            p.daylen = i - p.dayi;
                            p.state_date = DateState::YearDashDashWs;
                            p.state_time = TimeState::Start;
                            p.set_day();
                            break 'iter_runes;
                        }
                        'T' => {
                            p.daylen = i - p.dayi;
                            p.state_date = DateState::YearDashDashT;
                            p.state_time = TimeState::Start;
                            p.set_day();
                            break 'iter_runes;
                        }
                        _ => {}
                    }
                }
                DateState::YearDashDashT => {
                    // dateYearDashDashT
                    //  2006-01-02T15:04:05Z07:00
                    //  2020-08-17T17:00:00:000+0100
                }
                DateState::YearDashDashOffset => {
                    //  2020-07-20+00:00
                    if r == ':' {
                        p.set(p.offseti, "-07:00");
                    }
                }
                DateState::YearDashAlphaDash => {
                    // 2013-Feb-03
                    if r == '-' {
                        p.molen = i - p.moi;
                        p.set(p.moi, "Jan");
                        p.dayi = i + 1;
                    }
                }
                DateState::DigitDash => {
                    // 13-Feb-03
                    // 29-Jun-2016
                    if is_letter(r) {
                        p.state_date = DateState::DigitDashAlpha;
                        p.moi = i;
                    } else {
                        return (None, Some(unknown_err(datestr)));
                    }
                }
                DateState::DigitDashAlpha => {
                    // 13-Feb-03
                    // 28-Feb-03
                    // 29-Jun-2016
                    if r == '-' {
                        p.molen = i - p.moi;
                        p.set(p.moi, "Jan");
                        p.yeari = i + 1;
                        p.state_date = DateState::DigitDashAlphaDash;
                    }
                }
                DateState::DigitDashAlphaDash => {
                    // 13-Feb-03   ambiguous
                    // 28-Feb-03   ambiguous
                    // 29-Jun-2016  dd-month(alpha)-yyyy
                    if r == ' ' {
                        // we need to find if this was 4 digits, aka year
                        // or 2 digits which makes it ambiguous year/day
                        let length = i - (p.moi + p.molen + 1);
                        if length == 4 {
                            p.yearlen = 4;
                            p.set(p.yeari, "2006");
                            // We now also know that part1 was the day
                            p.dayi = 0;
                            p.daylen = p.part1_len;
                            p.set_day();
                        } else if length == 2 {
                            // We have no idea if this is
                            // yy-mon-dd   OR  dd-mon-yy
                            //
                            // We are going to ASSUME (bad, bad) that it is dd-mon-yy  which is a horible assumption
                            p.ambiguous_md = true;
                            p.yearlen = 2;
                            p.set(p.yeari, "06");
                            // We now also know that part1 was the day
                            p.dayi = 0;
                            p.daylen = p.part1_len;
                            p.set_day();
                        }
                        p.state_time = TimeState::Start;
                        break 'iter_runes;
                    }
                }
                DateState::DigitYearSlash => {
                    // 2014/07/10 06:55:38.156283
                    // I honestly don't know if this format ever shows up as yyyy/
                    match r {
                        ' ' | ':' => {
                            p.state_time = TimeState::Start;
                            if p.daylen == 0 {
                                p.daylen = i - p.dayi;
                                p.set_day();
                            }
                            break 'iter_runes;
                        }
                        '/' if p.molen == 0 => {
                            p.molen = i - p.moi;
                            p.set_month();
                            p.dayi = i + 1;
                        }
                        _ => {}
                    }
                }
                DateState::DigitSlashAlpha => {
                    // 06/May/2008
                    match r {
                        '/' => {
                            //       |
                            // 06/May/2008
                            if p.molen == 0 {
                                p.set(p.moi, "Jan");
                                p.yeari = i + 1;
                            }
                            // We aren't breaking because we are going to re-use this case
                            // to find where the date starts, and possible time begins
                        }
                        ' ' | ':' => {
                            p.state_time = TimeState::Start;
                            if p.yearlen == 0 {
                                p.yearlen = i - p.yeari;
                                p.set_year();
                            }
                            break 'iter_runes;
                        }
                        _ => {}
                    }
                }
                DateState::DigitSlash => {
                    // 03/19/2012 10:11:59
                    // 04/2/2014 03:00:37
                    // 3/1/2012 10:11:59
                    // 4/8/2014 22:05
                    // 3/1/2014
                    // 10/13/2014
                    // 01/02/2006
                    // 1/2/06
                    match r {
                        '/' => {
                            // This is the 2nd / so now we should know start pts of all of the dd, mm, yy
                            if p.prefer_month_first {
                                if p.daylen == 0 {
                                    p.daylen = i - p.dayi;
                                    p.set_day();
                                    p.yeari = i + 1;
                                }
                            } else if p.molen == 0 {
                                p.molen = i - p.moi;
                                p.set_month();
                                p.yeari = i + 1;
                            }
                            // Note no break, we are going to pass by and re-enter this dateDigitSlash
                            // and look for ending (space) or not (just date)
                        }
                        ' ' => {
                            p.state_time = TimeState::Start;
                            if p.yearlen == 0 {
                                p.yearlen = i - p.yeari;
                                p.set_year();
                            }
                            break 'iter_runes;
                        }
                        _ => {}
                    }
                }
                DateState::DigitColon => {
                    // 2014:07:10 06:55:38.156283
                    // 03:19:2012 10:11:59
                    // 04:2:2014 03:00:37
                    // 3:1:2012 10:11:59
                    // 4:8:2014 22:05
                    // 3:1:2014
                    // 10:13:2014
                    // 01:02:2006
                    // 1:2:06
                    match r {
                        ' ' => {
                            p.state_time = TimeState::Start;
                            if p.yearlen == 0 {
                                p.yearlen = i - p.yeari;
                                p.set_year();
                            } else if p.daylen == 0 {
                                p.daylen = i - p.dayi;
                                p.set_day();
                            }
                            break 'iter_runes;
                        }
                        ':' => {
                            if p.yearlen > 0 {
                                // 2014:07:10 06:55:38.156283
                                if p.molen == 0 {
                                    p.molen = i - p.moi;
                                    p.set_month();
                                    p.dayi = i + 1;
                                }
                            } else if p.prefer_month_first && p.daylen == 0 {
                                p.daylen = i - p.dayi;
                                p.set_day();
                                p.yeari = i + 1;
                            }
                        }
                        _ => {}
                    }
                }
                DateState::DigitWs => {
                    // 18 January 2018
                    // 8 January 2018
                    // 8 jan 2018
                    // 1 jan 18
                    // 02 Jan 2018 23:59
                    // 02 Jan 2018 23:59:34
                    // 12 Feb 2006, 19:17
                    // 12 Feb 2006, 19:17:22
                    if r == ' ' {
                        p.yeari = i + 1;
                        //p.yearlen = 4
                        p.dayi = 0;
                        p.daylen = p.part1_len;
                        p.set_day();
                        p.state_time = TimeState::Start;
                        if i > p.daylen + golen(b" Sep") {
                            //  November etc
                            // If len greather than space + 3 it must be full month
                            p.state_date = DateState::DigitWsMolong;
                        } else {
                            // If len=3, the might be Feb or May?  Ie ambigous abbreviated but
                            // we can parse may with either.  BUT, that means the
                            // format may not be correct?
                            // mo := strings.ToLower(datestr[p.daylen+1 : i])
                            p.moi = p.daylen + 1;
                            p.molen = i - p.moi;
                            p.set(p.moi, "Jan");
                            p.state_date = DateState::DigitWsMoYear;
                        }
                    }
                }
                DateState::DigitWsMoYear => {
                    // 8 jan 2018
                    // 02 Jan 2018 23:59
                    // 02 Jan 2018 23:59:34
                    // 12 Feb 2006, 19:17
                    // 12 Feb 2006, 19:17:22
                    match r {
                        ',' => {
                            p.yearlen = i - p.yeari;
                            p.set_year();
                            i += 1;
                            break 'iter_runes;
                        }
                        ' ' => {
                            p.yearlen = i - p.yeari;
                            p.set_year();
                            break 'iter_runes;
                        }
                        _ => {}
                    }
                }
                DateState::DigitWsMolong => {
                    // 18 January 2018
                    // 8 January 2018
                }
                DateState::DigitChineseYear => {
                    // dateDigitChineseYear
                    //   2014年04月08日
                    //               weekday  %Y年%m月%e日 %A %I:%M %p
                    // 2013年07月18日 星期四 10:27 上午
                    if r == ' ' {
                        p.state_date = DateState::DigitChineseYearWs;
                    }
                }
                DateState::DigitDot => {
                    // This is the 2nd period
                    // 3.31.2014
                    // 08.21.71
                    // 2014.05
                    // 2018.09.30
                    if r == '.' {
                        if p.moi == 0 {
                            // 3.31.2014
                            p.daylen = i - p.dayi;
                            p.yeari = i + 1;
                            p.set_day();
                            p.state_date = DateState::DigitDotDot;
                        } else {
                            // 2018.09.30
                            //p.molen = 2
                            p.molen = i - p.moi;
                            p.dayi = i + 1;
                            p.set_month();
                            p.state_date = DateState::DigitDotDot;
                        }
                    }
                }
                DateState::DigitDotDot => {
                    // iterate all the way through
                }
                DateState::Alpha => {
                    // dateAlphaWS
                    //  Mon Jan _2 15:04:05 2006
                    //  Mon Jan _2 15:04:05 MST 2006
                    //  Mon Jan 02 15:04:05 -0700 2006
                    //  Mon Aug 10 15:44:11 UTC+0100 2015
                    //  Fri Jul 03 2015 18:04:07 GMT+0100 (GMT Daylight Time)
                    //  dateAlphaWSDigit
                    //    May 8, 2009 5:57:51 PM
                    //    oct 1, 1970
                    //  dateAlphaWsMonth
                    //    April 8, 2009
                    //  dateAlphaWsMore
                    //    dateAlphaWsAtTime
                    //      January 02, 2006 at 3:04pm MST-07
                    //
                    //  dateAlphaPeriodWsDigit
                    //    oct. 1, 1970
                    // dateWeekdayComma
                    //   Monday, 02 Jan 2006 15:04:05 MST
                    //   Monday, 02-Jan-06 15:04:05 MST
                    //   Monday, 02 Jan 2006 15:04:05 -0700
                    //   Monday, 02 Jan 2006 15:04:05 +0100
                    // dateWeekdayAbbrevComma
                    //   Mon, 02 Jan 2006 15:04:05 MST
                    //   Mon, 02 Jan 2006 15:04:05 -0700
                    //   Thu, 13 Jul 2017 08:58:40 +0100
                    //   Tue, 11 Jul 2017 16:28:13 +0200 (CEST)
                    //   Mon, 02-Jan-06 15:04:05 MST
                    match r {
                        ' ' => {
                            //      X
                            // April 8, 2009
                            if i > 3 {
                                // Check to see if the alpha is name of month?  or Day?
                                if let Some(month) =
                                    to_lower(&datestr[..ix(i)]).filter(|m| is_month_full(m))
                                {
                                    p.full_month = month;
                                    // len(" 31, 2018")   = 9
                                    if golen(&datestr[ix(i)..]) < 10 {
                                        // April 8, 2009
                                        p.state_date = DateState::AlphaWsMonth;
                                    } else {
                                        p.state_date = DateState::AlphaWsMore;
                                    }
                                    p.dayi = i + 1;
                                }
                            } else {
                                // This is possibly ambiguous?  May will parse as either though.
                                // So, it could return in-correct format.
                                // dateAlphaWs
                                //   May 05, 2005, 05:05:05
                                //   May 05 2005, 05:05:05
                                //   Jul 05, 2005, 05:05:05
                                //   May 8 17:57:51 2009
                                //   May  8 17:57:51 2009
                                // skip & return to dateStart
                                //   Tue 05 May 2020, 05:05:05
                                //   Mon Jan  2 15:04:05 2006

                                if to_lower(&datestr[..ix(i)]).is_some_and(|d| is_day(&d)) {
                                    // using skip throws off indices used by other code; saner to restart
                                    // (Go drops the options here.)
                                    return parse_time(&datestr[ix(i + 1)..], loc, &[]);
                                }
                                p.state_date = DateState::AlphaWs;
                            }
                        }
                        ',' => {
                            // Mon, 02 Jan 2006

                            if i == 3 {
                                p.state_date = DateState::WeekdayAbbrevComma;
                                p.set(0, "Mon");
                            } else {
                                p.state_date = DateState::WeekdayComma;
                                p.skip = i + 2;
                                i += 1;
                                // TODO:  lets just make this "skip" as we don't need
                                // the mon, monday, they are all superfelous and not needed
                                // just lay down the skip, no need to fill and then skip
                            }
                        }
                        '.' => {
                            // sept. 28, 2017
                            // jan. 28, 2017
                            p.state_date = DateState::AlphaPeriodWsDigit;
                            if i == 3 {
                                p.molen = i;
                                p.set(0, "Jan");
                            } else if i == 4 {
                                // gross
                                *datestr = [&datestr[..ix(i - 1)], &datestr[ix(i)..]].concat();
                                return parse_time(datestr, loc, opts);
                            } else {
                                return (None, Some(unknown_err(datestr)));
                            }
                        }
                        _ => {}
                    }
                }
                DateState::AlphaWs => {
                    // dateAlphaWsAlpha
                    //   Mon Jan _2 15:04:05 2006
                    //   Mon Jan _2 15:04:05 MST 2006
                    //   Mon Jan 02 15:04:05 -0700 2006
                    //   Fri Jul 03 2015 18:04:07 GMT+0100 (GMT Daylight Time)
                    //   Mon Aug 10 15:44:11 UTC+0100 2015
                    // dateAlphaWsDigit
                    //   May 8, 2009 5:57:51 PM
                    //   May 8 2009 5:57:51 PM
                    //   May 8 17:57:51 2009
                    //   May  8 17:57:51 2009
                    //   May 08 17:57:51 2009
                    //   oct 1, 1970
                    //   oct 7, '70
                    if is_letter(r) {
                        p.set(0, "Mon");
                        p.state_date = DateState::AlphaWsAlpha;
                        p.set(i, "Jan");
                    } else if is_digit(r) {
                        p.set(0, "Jan");
                        p.state_date = DateState::AlphaWsDigit;
                        p.dayi = i;
                    }
                }
                DateState::AlphaWsDigit => {
                    // May 8, 2009 5:57:51 PM
                    // May 8 2009 5:57:51 PM
                    // oct 1, 1970
                    // oct 7, '70
                    // oct. 7, 1970
                    // May 8 17:57:51 2009
                    // May  8 17:57:51 2009
                    // May 08 17:57:51 2009
                    if r == ',' {
                        p.daylen = i - p.dayi;
                        p.set_day();
                        p.state_date = DateState::AlphaWsDigitMore;
                    } else if r == ' ' {
                        p.daylen = i - p.dayi;
                        p.set_day();
                        p.yeari = i + 1;
                        p.state_date = DateState::AlphaWsDigitYearmaybe;
                        p.state_time = TimeState::Start;
                    } else if is_letter(r) {
                        p.state_date = DateState::AlphaWsMonthSuffix;
                        i -= 1;
                    }
                }
                DateState::AlphaWsDigitYearmaybe => {
                    //       x
                    // May 8 2009 5:57:51 PM
                    // May 8 17:57:51 2009
                    // May  8 17:57:51 2009
                    // May 08 17:57:51 2009
                    // Jul 03 2015 18:04:07 GMT+0100 (GMT Daylight Time)
                    if r == ':' {
                        // Guessed wrong; was not a year
                        i -= 3;
                        p.state_date = DateState::AlphaWsDigit;
                        p.yeari = 0;
                        break 'iter_runes;
                    } else if r == ' ' {
                        // must be year format, not 15:04
                        p.yearlen = i - p.yeari;
                        p.set_year();
                        break 'iter_runes;
                    }
                }
                DateState::AlphaWsDigitMore => {
                    //       x
                    // May 8, 2009 5:57:51 PM
                    // May 05, 2005, 05:05:05
                    // May 05 2005, 05:05:05
                    // oct 1, 1970
                    // oct 7, '70
                    if r == ' ' {
                        p.yeari = i + 1;
                        p.state_date = DateState::AlphaWsDigitMoreWs;
                    }
                }
                DateState::AlphaWsDigitMoreWs => {
                    //            x
                    // May 8, 2009 5:57:51 PM
                    // May 05, 2005, 05:05:05
                    // oct 1, 1970
                    // oct 7, '70
                    match r {
                        '\'' => p.yeari = i + 1,
                        ' ' | ',' => {
                            //            x
                            // May 8, 2009 5:57:51 PM
                            //            x
                            // May 8, 2009, 5:57:51 PM
                            p.state_date = DateState::AlphaWsDigitMoreWsYear;
                            p.yearlen = i - p.yeari;
                            p.set_year();
                            p.state_time = TimeState::Start;
                            break 'iter_runes;
                        }
                        _ => {}
                    }
                }
                DateState::AlphaWsMonth => {
                    // April 8, 2009
                    // April 8 2009
                    match r {
                        ' ' | ',' => {
                            //       x
                            // June 8, 2009
                            //       x
                            // June 8 2009
                            if p.daylen == 0 {
                                p.daylen = i - p.dayi;
                                p.set_day();
                            }
                        }
                        's' | 'S' | 'r' | 'R' | 't' | 'T' | 'n' | 'N' => {
                            // st, rd, nd, st
                            i -= 1;
                            p.state_date = DateState::AlphaWsMonthSuffix;
                        }
                        _ => {
                            if p.daylen > 0 && p.yeari == 0 {
                                p.yeari = i;
                            }
                        }
                    }
                }
                DateState::AlphaWsMonthMore => {
                    //                  X
                    // January 02, 2006, 15:04:05
                    // January 02 2006, 15:04:05
                    // January 02, 2006 15:04:05
                    // January 02 2006 15:04:05
                    match r {
                        ',' => {
                            p.yearlen = i - p.yeari;
                            p.set_year();
                            p.state_time = TimeState::Start;
                            i += 1;
                            break 'iter_runes;
                        }
                        ' ' => {
                            p.yearlen = i - p.yeari;
                            p.set_year();
                            p.state_time = TimeState::Start;
                            break 'iter_runes;
                        }
                        _ => {}
                    }
                }
                DateState::AlphaWsMonthSuffix => {
                    //        x
                    // April 8th, 2009
                    // April 8th 2009
                    // The four suffixes st, nd, rd and th: each case of Go's
                    // switch tests its second letter in either case, then
                    // restarts without the suffix.
                    let second = match r {
                        't' | 'T' => Some((b'h', b'H')),
                        'n' | 'N' => Some((b'd', b'D')),
                        's' | 'S' => Some((b't', b'T')),
                        'r' | 'R' => Some((b'd', b'D')),
                        _ => None,
                    };
                    if let Some((lower, upper)) = second
                        && (p.next_is(i, lower) || p.next_is(i, upper))
                        && golen(datestr) > i + 2
                    {
                        let ds = [&p.datestr[..ix(i)], &p.datestr[ix(i + 2)..]].concat();
                        return parse_time(&ds, loc, opts);
                    }
                }
                DateState::AlphaWsMore => {
                    // January 02, 2006, 15:04:05
                    // January 02 2006, 15:04:05
                    // January 2nd, 2006, 15:04:05
                    // January 2nd 2006, 15:04:05
                    // September 17, 2012 at 5:00pm UTC-05
                    if r == ',' {
                        //           x
                        // January 02, 2006, 15:04:05
                        if p.next_is(i, b' ') {
                            p.daylen = i - p.dayi;
                            p.set_day();
                            p.yeari = i + 2;
                            p.state_date = DateState::AlphaWsMonthMore;
                            i += 1;
                        }
                    } else if r == ' ' {
                        //           x
                        // January 02 2006, 15:04:05
                        p.daylen = i - p.dayi;
                        p.set_day();
                        p.yeari = i + 1;
                        p.state_date = DateState::AlphaWsMonthMore;
                    } else if is_digit(r) {
                        //         XX
                        // January 02, 2006, 15:04:05
                        break 'next;
                    } else if is_letter(r) {
                        //          X
                        // January 2nd, 2006, 15:04:05
                        p.daylen = i - p.dayi;
                        p.set_day();
                        p.state_date = DateState::AlphaWsMonthSuffix;
                        i -= 1;
                    }
                }
                DateState::AlphaPeriodWsDigit => {
                    //    oct. 7, '70
                    if r == ' ' {
                        // continue
                    } else if is_digit(r) {
                        p.state_date = DateState::AlphaWsDigit;
                        p.dayi = i;
                    } else {
                        let err = unknown_err(datestr);
                        return (Some(p), Some(err));
                    }
                }
                DateState::WeekdayComma => {
                    // Monday, 02 Jan 2006 15:04:05 MST
                    // Monday, 02 Jan 2006 15:04:05 -0700
                    // Monday, 02 Jan 2006 15:04:05 +0100
                    // Monday, 02-Jan-06 15:04:05 MST
                    if p.dayi == 0 {
                        p.dayi = i;
                    }
                    if r == ' ' || r == '-' {
                        if p.moi == 0 {
                            p.moi = i + 1;
                            p.daylen = i - p.dayi;
                            p.set_day();
                        } else if p.yeari == 0 {
                            p.yeari = i + 1;
                            p.molen = i - p.moi;
                            p.set(p.moi, "Jan");
                        } else {
                            p.state_time = TimeState::Start;
                            break 'iter_runes;
                        }
                    }
                }
                DateState::WeekdayAbbrevComma => {
                    // Mon, 02 Jan 2006 15:04:05 MST
                    // Mon, 02 Jan 2006 15:04:05 -0700
                    // Thu, 13 Jul 2017 08:58:40 +0100
                    // Thu, 4 Jan 2018 17:53:36 +0000
                    // Tue, 11 Jul 2017 16:28:13 +0200 (CEST)
                    // Mon, 02-Jan-06 15:04:05 MST
                    if r == ' ' || r == '-' {
                        if p.dayi == 0 {
                            p.dayi = i + 1;
                        } else if p.moi == 0 {
                            p.daylen = i - p.dayi;
                            p.set_day();
                            p.moi = i + 1;
                        } else if p.yeari == 0 {
                            p.molen = i - p.moi;
                            p.set(p.moi, "Jan");
                            p.yeari = i + 1;
                        } else {
                            p.yearlen = i - p.yeari;
                            p.set_year();
                            p.state_time = TimeState::Start;
                            break 'iter_runes;
                        }
                    }
                }
                // Go's default case.
                DateState::YearDashDashWs
                | DateState::DigitChineseYearWs
                | DateState::AlphaWsAlpha
                | DateState::AlphaWsDigitMoreWsYear => break 'iter_runes,
            }
        }
        i += 1;
    }
    p.coalesce_date(i);
    if p.state_time == TimeState::Start {
        // increment first one, since the i++ occurs at end of loop
        if i < golen(&p.datestr) {
            i += 1;
        }
        // ensure we skip any whitespace prefix
        while i < golen(datestr) && datestr[ix(i)] == b' ' {
            i += 1;
        }

        'iter_time_runes: while i < golen(datestr) {
            // Go reads a byte here, as a rune: 0xC3 is 'Ã', a letter.
            let r = char::from(datestr[ix(i)]);

            match p.state_time {
                TimeState::Start => {
                    // 22:43:22
                    // 22:43
                    // timeComma
                    //   08:20:13,787
                    // timeWs
                    //   05:24:37 PM
                    //   06:20:00 UTC
                    //   06:20:00 UTC-05
                    //   00:12:00 +0000 UTC
                    //   22:18:00 +0000 UTC m=+0.000000001
                    //   15:04:05 -0700
                    //   15:04:05 -07:00
                    //   15:04:05 2008
                    // timeOffset
                    //   03:21:51+00:00
                    //   19:55:00+0100
                    // timePeriod
                    //   17:24:37.3186369
                    //   00:07:31.945167
                    //   18:31:59.257000000
                    //   00:00:00.000
                    //   timePeriodOffset
                    //     19:55:00.799+0100
                    //     timePeriodOffsetColon
                    //       15:04:05.999-07:00
                    //   timePeriodWs
                    //     timePeriodWsOffset
                    //       00:07:31.945167 +0000
                    //       00:00:00.000 +0000
                    //     timePeriodWsOffsetAlpha
                    //       00:07:31.945167 +0000 UTC
                    //       22:18:00.001 +0000 UTC m=+0.000000001
                    //       00:00:00.000 +0000 UTC
                    //     timePeriodWsAlpha
                    //       06:20:00.000 UTC
                    if p.houri == 0 {
                        p.houri = i;
                    }
                    match r {
                        ',' => {
                            // hm, lets just swap out comma for period.  for some reason go
                            // won't parse it.
                            // 2014-05-11 08:20:13,787
                            let mut ds = p.datestr.clone();
                            ds[ix(i)] = b'.';
                            return parse_time(&ds, loc, opts);
                        }
                        '-' | '+' => {
                            //   03:21:51+00:00
                            p.state_time = TimeState::Offset;
                            if p.seci == 0 {
                                // 22:18+0530
                                p.minlen = i - p.mini;
                            } else {
                                if p.seclen == 0 {
                                    p.seclen = i - p.seci;
                                }
                                if p.msi > 0 && p.mslen == 0 {
                                    p.mslen = i - p.msi;
                                }
                            }
                            p.offseti = i;
                        }
                        '.' => {
                            p.state_time = TimeState::Period;
                            p.seclen = i - p.seci;
                            p.msi = i + 1;
                        }
                        'Z' => {
                            p.state_time = TimeState::Z;
                            if p.seci == 0 {
                                p.minlen = i - p.mini;
                            } else {
                                p.seclen = i - p.seci;
                            }
                            // (Z)ulu time
                            p.loc = Some(gotime::utc());
                        }
                        'a' | 'A' => {
                            if p.next_is(i, b't') || p.next_is(i, b'T') {
                                //                    x
                                // September 17, 2012 at 5:00pm UTC-05
                                i += 1; // skip t
                                if p.next_is(i, b' ') {
                                    //                      x
                                    // September 17, 2012 at 5:00pm UTC-05
                                    i += 1; // skip '
                                    p.houri = 0; // reset hour
                                }
                            } else if r == 'a' && p.next_is(i, b'm') {
                                p.coalesce_time(i);
                                p.set(i, "am");
                            } else if r == 'A' && p.next_is(i, b'M') {
                                p.coalesce_time(i);
                                p.set(i, "PM");
                            }
                        }
                        'p' | 'P' => {
                            // Could be AM/PM
                            if r == 'p' && p.next_is(i, b'm') {
                                p.coalesce_time(i);
                                p.set(i, "pm");
                            } else if r == 'P' && p.next_is(i, b'M') {
                                p.coalesce_time(i);
                                p.set(i, "PM");
                            }
                        }
                        ' ' => {
                            p.coalesce_time(i);
                            p.state_time = TimeState::Ws;
                        }
                        ':' => {
                            if p.mini == 0 {
                                p.mini = i + 1;
                                p.hourlen = i - p.houri;
                            } else if p.seci == 0 {
                                p.seci = i + 1;
                                p.minlen = i - p.mini;
                            } else if p.seci > 0 {
                                // 18:31:59:257    ms uses colon, wtf
                                p.seclen = i - p.seci;
                                p.set(p.seci, "05");
                                p.msi = i + 1;

                                // gross, gross, gross.   manipulating the datestr is horrible.
                                // https://github.com/araddon/dateparse/issues/117
                                // Could not get the parsing to work using golang time.Parse() without
                                // replacing that colon with period.
                                p.set(i, ".");
                                *datestr =
                                    [&datestr[..ix(i)], b".", &datestr[ix(i + 1)..]].concat();
                                p.datestr = datestr.clone();
                            }
                        }
                        _ => {}
                    }
                }
                TimeState::Offset => {
                    // 19:55:00+0100
                    // timeOffsetColon
                    //   15:04:05+07:00
                    //   15:04:05-07:00
                    if r == ':' {
                        p.state_time = TimeState::OffsetColon;
                    }
                }
                TimeState::Ws => {
                    // timeWsAlpha
                    //   06:20:00 UTC
                    //   06:20:00 UTC-05
                    //   15:44:11 UTC+0100 2015
                    //   18:04:07 GMT+0100 (GMT Daylight Time)
                    //   17:57:51 MST 2009
                    //   timeWsAMPMMaybe
                    //     05:24:37 PM
                    // timeWsOffset
                    //   15:04:05 -0700
                    //   00:12:00 +0000 UTC
                    //   timeWsOffsetColon
                    //     15:04:05 -07:00
                    //     17:57:51 -0700 2009
                    //     timeWsOffsetColonAlpha
                    //       00:12:00 +00:00 UTC
                    // timeWsYear
                    //     00:12:00 2008
                    // timeZ
                    //   15:04:05.99Z
                    match r {
                        'A' | 'P' => {
                            // Could be AM/PM or could be PST or similar
                            p.tzi = i;
                            p.state_time = TimeState::WsAmPmMaybe;
                        }
                        '+' | '-' => {
                            p.offseti = i;
                            p.state_time = TimeState::WsOffset;
                        }
                        _ => {
                            if is_letter(r) {
                                // 06:20:00 UTC
                                // 06:20:00 UTC-05
                                // 15:44:11 UTC+0100 2015
                                // 17:57:51 MST 2009
                                p.tzi = i;
                                p.state_time = TimeState::WsAlpha;
                            } else if is_digit(r) {
                                // 00:12:00 2008
                                p.state_time = TimeState::WsYear;
                                p.yeari = i;
                            }
                        }
                    }
                }
                TimeState::WsAlpha => {
                    // 06:20:00 UTC
                    // 06:20:00 UTC-05
                    // timeWsAlphaWs
                    //   17:57:51 MST 2009
                    // timeWsAlphaZoneOffset
                    // timeWsAlphaZoneOffsetWs
                    //   timeWsAlphaZoneOffsetWsExtra
                    //     18:04:07 GMT+0100 (GMT Daylight Time)
                    //   timeWsAlphaZoneOffsetWsYear
                    //     15:44:11 UTC+0100 2015
                    match r {
                        '+' | '-' => {
                            p.tzlen = i - p.tzi;
                            if p.tzlen == 4 {
                                p.set(p.tzi, " MST");
                            } else if p.tzlen == 3 {
                                p.set(p.tzi, "MST");
                            }
                            p.state_time = TimeState::WsAlphaZoneOffset;
                            p.offseti = i;
                        }
                        ' ' => {
                            // 17:57:51 MST 2009
                            // 17:57:51 MST
                            p.tzlen = i - p.tzi;
                            if p.tzlen == 4 {
                                p.set(p.tzi, " MST");
                            } else if p.tzlen == 3 {
                                p.set(p.tzi, "MST");
                            }
                            p.state_time = TimeState::WsAlphaWs;
                            p.yeari = i + 1;
                        }
                        _ => {}
                    }
                }
                TimeState::WsAlphaWs => {
                    //   17:57:51 MST 2009
                }
                TimeState::WsAlphaZoneOffset => {
                    // 06:20:00 UTC-05
                    // timeWsAlphaZoneOffset
                    // timeWsAlphaZoneOffsetWs
                    //   timeWsAlphaZoneOffsetWsExtra
                    //     18:04:07 GMT+0100 (GMT Daylight Time)
                    //   timeWsAlphaZoneOffsetWsYear
                    //     15:44:11 UTC+0100 2015
                    if r == ' ' {
                        p.set(p.offseti, "-0700");
                        if p.yeari == 0 {
                            p.yeari = i + 1;
                        }
                        p.state_time = TimeState::WsAlphaZoneOffsetWs;
                    }
                }
                TimeState::WsAlphaZoneOffsetWs => {
                    // timeWsAlphaZoneOffsetWs
                    //   timeWsAlphaZoneOffsetWsExtra
                    //     18:04:07 GMT+0100 (GMT Daylight Time)
                    //   timeWsAlphaZoneOffsetWsYear
                    //     15:44:11 UTC+0100 2015
                    if is_digit(r) {
                        p.state_time = TimeState::WsAlphaZoneOffsetWsYear;
                    } else {
                        p.extra = i - 1;
                        p.state_time = TimeState::WsAlphaZoneOffsetWsExtra;
                    }
                }
                TimeState::WsAlphaZoneOffsetWsYear => {
                    // 15:44:11 UTC+0100 2015
                    if is_digit(r) {
                        p.yearlen = i - p.yeari + 1;
                        if p.yearlen == 4 {
                            p.set_year();
                        }
                    }
                }
                TimeState::WsAmPmMaybe => {
                    // timeWsAMPMMaybe
                    //   timeWsAMPM
                    //     05:24:37 PM
                    //   timeWsAlpha
                    //     00:12:00 PST
                    //     15:44:11 UTC+0100 2015
                    if r == 'M' {
                        //return parse("2006-01-02 03:04:05 PM", datestr, loc)
                        p.state_time = TimeState::WsAmPm;
                        p.set(i - 1, "PM");
                        if p.hourlen == 2 {
                            p.set(p.houri, "03");
                        } else if p.hourlen == 1 {
                            p.set(p.houri, "3");
                        }
                    } else {
                        p.state_time = TimeState::WsAlpha;
                    }
                }
                TimeState::WsOffset => {
                    // timeWsOffset
                    //   15:04:05 -0700
                    //   timeWsOffsetWsOffset
                    //     17:57:51 -0700 -07
                    //   timeWsOffsetWs
                    //     17:57:51 -0700 2009
                    //     00:12:00 +0000 UTC
                    //   timeWsOffsetColon
                    //     15:04:05 -07:00
                    //     timeWsOffsetColonAlpha
                    //       00:12:00 +00:00 UTC
                    match r {
                        ':' => p.state_time = TimeState::WsOffsetColon,
                        ' ' => {
                            p.set(p.offseti, "-0700");
                            p.yeari = i + 1;
                            p.state_time = TimeState::WsOffsetWs;
                        }
                        _ => {}
                    }
                }
                TimeState::WsOffsetWs => {
                    // 17:57:51 -0700 2009
                    // 00:12:00 +0000 UTC
                    // 22:18:00.001 +0000 UTC m=+0.000000001
                    // w Extra
                    //   17:57:51 -0700 -07
                    match r {
                        '=' => {
                            // eff you golang
                            if datestr[ix(i - 1)] == b'm' {
                                p.extra = i - 2;
                                p.trim_extra();
                            }
                        }
                        '+' | '-' | '(' => {
                            // This really doesn't seem valid, but for some reason when round-tripping a go date
                            // their is an extra +03 printed out.  seems like go bug to me, but, parsing anyway.
                            // 00:00:00 +0300 +03
                            // 00:00:00 +0300 +0300
                            p.extra = i - 1;
                            p.state_time = TimeState::WsOffset;
                            p.trim_extra();
                        }
                        _ => {
                            if is_digit(r) {
                                p.yearlen = i - p.yeari + 1;
                                if p.yearlen == 4 {
                                    p.set_year();
                                }
                            } else if is_letter(r) {
                                // 15:04:05 -0700 MST
                                if p.tzi == 0 {
                                    p.tzi = i;
                                }
                            }
                        }
                    }
                }
                TimeState::WsOffsetColon => {
                    // timeWsOffsetColon
                    //   15:04:05 -07:00
                    //   timeWsOffsetColonAlpha
                    //     2015-02-18 00:12:00 +00:00 UTC
                    if is_letter(r) {
                        // 2015-02-18 00:12:00 +00:00 UTC
                        p.state_time = TimeState::WsOffsetColonAlpha;
                        break 'iter_time_runes;
                    }
                }
                TimeState::Period => {
                    // 15:04:05.999999999+07:00
                    // 15:04:05.999999999-07:00
                    // 15:04:05.999999+07:00
                    // 15:04:05.999999-07:00
                    // 15:04:05.999+07:00
                    // 15:04:05.999-07:00
                    // timePeriod
                    //   17:24:37.3186369
                    //   00:07:31.945167
                    //   18:31:59.257000000
                    //   00:00:00.000
                    //   timePeriodOffset
                    //     19:55:00.799+0100
                    //     timePeriodOffsetColon
                    //       15:04:05.999-07:00
                    //   timePeriodWs
                    //     timePeriodWsOffset
                    //       00:07:31.945167 +0000
                    //       00:00:00.000 +0000
                    //       With Extra
                    //         00:00:00.000 +0300 +03
                    //     timePeriodWsOffsetAlpha
                    //       00:07:31.945167 +0000 UTC
                    //       00:00:00.000 +0000 UTC
                    //       22:18:00.001 +0000 UTC m=+0.000000001
                    //     timePeriodWsAlpha
                    //       06:20:00.000 UTC
                    match r {
                        ' ' => {
                            p.mslen = i - p.msi;
                            p.state_time = TimeState::PeriodWs;
                        }
                        '+' | '-' => {
                            // This really shouldn't happen
                            p.mslen = i - p.msi;
                            p.offseti = i;
                            p.state_time = TimeState::PeriodOffset;
                        }
                        _ => {
                            if is_letter(r) {
                                // 06:20:00.000 UTC
                                p.mslen = i - p.msi;
                                p.state_time = TimeState::PeriodWsAlpha;
                            }
                        }
                    }
                }
                TimeState::PeriodOffset => {
                    // timePeriodOffset
                    //   19:55:00.799+0100
                    //   timePeriodOffsetColon
                    //     15:04:05.999-07:00
                    //     13:31:51.999-07:00 MST
                    if r == ':' {
                        p.state_time = TimeState::PeriodOffsetColon;
                    }
                }
                TimeState::PeriodOffsetColon => {
                    // timePeriodOffset
                    //   timePeriodOffsetColon
                    //     15:04:05.999-07:00
                    //     13:31:51.999 -07:00 MST
                    if r == ' ' {
                        p.set(p.offseti, "-07:00");
                        p.state_time = TimeState::PeriodOffsetColonWs;
                        p.tzi = i + 1;
                    }
                }
                TimeState::PeriodOffsetColonWs => {
                    // continue
                }
                TimeState::PeriodWs => {
                    // timePeriodWs
                    //   timePeriodWsOffset
                    //     00:07:31.945167 +0000
                    //     00:00:00.000 +0000
                    //   timePeriodWsOffsetAlpha
                    //     00:07:31.945167 +0000 UTC
                    //     00:00:00.000 +0000 UTC
                    //   timePeriodWsOffsetColon
                    //     13:31:51.999 -07:00 MST
                    //   timePeriodWsAlpha
                    //     06:20:00.000 UTC
                    if p.offseti == 0 {
                        p.offseti = i;
                    }
                    match r {
                        '+' | '-' => {
                            p.mslen = i - p.msi - 1;
                            p.state_time = TimeState::PeriodWsOffset;
                        }
                        _ => {
                            if is_letter(r) {
                                //     00:07:31.945167 +0000 UTC
                                //     00:00:00.000 +0000 UTC
                                p.state_time = TimeState::PeriodWsOffsetWsAlpha;
                                break 'iter_time_runes;
                            }
                        }
                    }
                }
                TimeState::PeriodWsOffset => {
                    // timePeriodWs
                    //   timePeriodWsOffset
                    //     00:07:31.945167 +0000
                    //     00:00:00.000 +0000
                    //     With Extra
                    //       00:00:00.000 +0300 +03
                    //   timePeriodWsOffsetAlpha
                    //     00:07:31.945167 +0000 UTC
                    //     00:00:00.000 +0000 UTC
                    //     03:02:00.001 +0300 MSK m=+0.000000001
                    //   timePeriodWsOffsetColon
                    //     13:31:51.999 -07:00 MST
                    //   timePeriodWsAlpha
                    //     06:20:00.000 UTC
                    match r {
                        ':' => p.state_time = TimeState::PeriodWsOffsetColon,
                        ' ' => p.set(p.offseti, "-0700"),
                        '+' | '-' => {
                            // This really doesn't seem valid, but for some reason when round-tripping a go date
                            // their is an extra +03 printed out.  seems like go bug to me, but, parsing anyway.
                            // 00:00:00.000 +0300 +03
                            // 00:00:00.000 +0300 +0300
                            p.extra = i - 1;
                            p.trim_extra();
                        }
                        _ => {
                            if is_letter(r) {
                                // 00:07:31.945167 +0000 UTC
                                // 00:00:00.000 +0000 UTC
                                // 03:02:00.001 +0300 MSK m=+0.000000001
                                p.state_time = TimeState::PeriodWsOffsetWsAlpha;
                            }
                        }
                    }
                }
                TimeState::PeriodWsOffsetWsAlpha => {
                    // 03:02:00.001 +0300 MSK m=+0.000000001
                    // eff you golang
                    if r == '=' && datestr[ix(i - 1)] == b'm' {
                        p.extra = i - 2;
                        p.trim_extra();
                    }
                }
                TimeState::PeriodWsOffsetColon => {
                    // 13:31:51.999 -07:00 MST
                    if r == ' ' {
                        p.set(p.offseti, "-07:00");
                    } else if is_letter(r) {
                        // 13:31:51.999 -07:00 MST
                        p.tzi = i;
                        p.state_time = TimeState::PeriodWsOffsetColonAlpha;
                    }
                }
                TimeState::PeriodWsOffsetColonAlpha => {
                    // continue
                }
                TimeState::Z => {
                    // timeZ
                    //   15:04:05.99Z
                    // With a time-zone at end after Z
                    // 2006-01-02T15:04:05.999999999Z07:00
                    // 2006-01-02T15:04:05Z07:00
                    // RFC3339     = "2006-01-02T15:04:05Z07:00"
                    // RFC3339Nano = "2006-01-02T15:04:05.999999999Z07:00"
                    if is_digit(r) {
                        p.state_time = TimeState::ZDigit;
                    }
                }
                // No case in Go's switch.
                TimeState::Ignore
                | TimeState::WsAlphaZoneOffsetWsExtra
                | TimeState::WsAmPm
                | TimeState::WsOffsetColonAlpha
                | TimeState::WsYear
                | TimeState::OffsetColon
                | TimeState::PeriodWsAlpha
                | TimeState::ZDigit => {}
            }
            i += 1;
        }

        match p.state_time {
            TimeState::WsAlpha => match golen(&p.datestr) - p.tzi {
                3 => {
                    // 13:31:51.999 +01:00 CET
                    p.set(p.tzi, "MST");
                }
                4 => {
                    p.set(p.tzi, "MST");
                    p.extra = golen(&p.datestr) - 1;
                    p.trim_extra();
                }
                _ => {}
            },
            TimeState::WsAlphaWs | TimeState::WsYear => {
                p.yearlen = i - p.yeari;
                p.set_year();
            }
            TimeState::WsAlphaZoneOffsetWsExtra => p.trim_extra(),
            TimeState::WsAlphaZoneOffset => {
                // 06:20:00 UTC-05
                if i - p.offseti < 4 {
                    p.set(p.offseti, "-07");
                } else {
                    p.set(p.offseti, "-0700");
                }
            }
            TimeState::Period => p.mslen = i - p.msi,
            TimeState::Offset => match golen(&p.datestr) - p.offseti {
                0..=2 | 4 => {
                    let err = Error::TzOffset {
                        datestr: datestr.clone(),
                        near: datestr[ix(p.offseti)..].to_vec(),
                    };
                    return (Some(p), Some(err));
                }
                3 => {
                    // 19:55:00+01
                    p.set(p.offseti, "-07");
                }
                5 => {
                    // 19:55:00+0100
                    p.set(p.offseti, "-0700");
                }
                _ => {}
            },
            TimeState::WsOffset => p.set(p.offseti, "-0700"),
            TimeState::WsOffsetWs => {
                // 17:57:51 -0700 2009
                // 00:12:00 +0000 UTC
                if p.tzi > 0 {
                    match golen(&p.datestr) - p.tzi {
                        3 => {
                            // 13:31:51.999 +01:00 CET
                            p.set(p.tzi, "MST");
                        }
                        4 => {
                            // 13:31:51.999 +01:00 CEST
                            p.set(p.tzi, "MST ");
                        }
                        _ => {}
                    }
                }
            }
            TimeState::WsOffsetColon => {
                // 17:57:51 -07:00
                p.set(p.offseti, "-07:00");
            }
            TimeState::OffsetColon => {
                // 15:04:05+07:00
                p.set(p.offseti, "-07:00");
            }
            TimeState::PeriodOffset => {
                // 19:55:00.799+0100
                p.set(p.offseti, "-0700");
            }
            TimeState::PeriodOffsetColon => p.set(p.offseti, "-07:00"),
            TimeState::PeriodWsOffsetColonAlpha => {
                p.tzlen = i - p.tzi;
                match p.tzlen {
                    3 => p.set(p.tzi, "MST"),
                    4 => p.set(p.tzi, "MST "),
                    _ => {}
                }
            }
            TimeState::PeriodWsOffset => p.set(p.offseti, "-0700"),
            _ => {}
        }
        p.coalesce_time(i);
    }

    match p.state_date {
        DateState::Digit => {
            // unixy timestamps ish
            //  example              ct type
            //  1499979655583057426  19 nanoseconds
            //  1499979795437000     16 micro-seconds
            //  20180722105203       14 yyyyMMddhhmmss
            //  1499979795437        13 milliseconds
            //  1332151919           10 seconds
            //  20140601             8  yyyymmdd
            //  2014                 4  yyyy
            let mut t = Time::default();
            let n = golen(datestr);
            if n == golen(b"1499979655583057426") {
                // 19
                // nano-seconds
                if let Some(nano_secs) = parse_int(datestr) {
                    t = gotime::unix(0, nano_secs);
                }
            } else if n == golen(b"1499979795437000") {
                // 16
                // micro-seconds
                if let Some(micro_secs) = parse_int(datestr) {
                    t = gotime::unix(0, micro_secs.wrapping_mul(1000));
                }
            } else if n == golen(b"yyyyMMddhhmmss") {
                // 14
                // yyyyMMddhhmmss
                p.format = b"20060102150405".to_vec();
                return (Some(p), None);
            } else if n == golen(b"1332151919000") {
                // 13
                if let Some(mili_secs) = parse_int(datestr) {
                    t = gotime::unix(0, mili_secs.wrapping_mul(1000).wrapping_mul(1000));
                }
            } else if n == golen(b"1332151919") {
                // 10
                if let Some(secs) = parse_int(datestr) {
                    t = gotime::unix(secs, 0);
                }
            } else if n == golen(b"20140601") {
                p.format = b"20060102".to_vec();
                return (Some(p), None);
            } else if n == golen(b"2014") {
                p.format = b"2006".to_vec();
                return (Some(p), None);
            } else if n < 4 {
                return (None, Some(Error::TooShort(datestr.clone())));
            }
            if !t.is_zero() {
                match loc {
                    None => p.t = Some(t),
                    Some(loc) => p.t = Some(t.in_location(loc)),
                }
                return (Some(p), None);
            }
        }
        DateState::DigitSt => {
            // 171113 14:14:20
            return (Some(p), None);
        }
        DateState::YearDash => {
            // 2006-01
            return (Some(p), None);
        }
        DateState::YearDashDash => {
            // 2006-01-02
            // 2006-1-02
            // 2006-1-2
            // 2006-01-2
            return (Some(p), None);
        }
        DateState::YearDashDashOffset => {
            //  2020-07-20+00:00
            match golen(&p.datestr) - p.offseti {
                5 => p.set(p.offseti, "-0700"),
                6 => p.set(p.offseti, "-07:00"),
                _ => {}
            }
            return (Some(p), None);
        }
        DateState::YearDashAlphaDash => {
            // 2013-Feb-03
            // 2013-Feb-3
            p.daylen = i - p.dayi;
            p.set_day();
            return (Some(p), None);
        }
        DateState::YearDashDashWs => {
            // 2013-04-01
            return (Some(p), None);
        }
        DateState::YearDashDashT => return (Some(p), None),
        DateState::DigitDashAlphaDash => {
            // 13-Feb-03   ambiguous
            // 28-Feb-03   ambiguous
            // 29-Jun-2016
            let length = golen(datestr) - (p.moi + p.molen + 1);
            if length == 4 {
                p.yearlen = 4;
                p.set(p.yeari, "2006");
                // We now also know that part1 was the day
                p.dayi = 0;
                p.daylen = p.part1_len;
                p.set_day();
            } else if length == 2 {
                // We have no idea if this is
                // yy-mon-dd   OR  dd-mon-yy
                //
                // We are going to ASSUME (bad, bad) that it is dd-mon-yy  which is a horible assumption
                p.ambiguous_md = true;
                p.yearlen = 2;
                p.set(p.yeari, "06");
                // We now also know that part1 was the day
                p.dayi = 0;
                p.daylen = p.part1_len;
                p.set_day();
            }

            return (Some(p), None);
        }
        DateState::DigitDot => {
            // 2014.05
            p.molen = i - p.moi;
            p.set_month();
            return (Some(p), None);
        }
        DateState::DigitDotDot => {
            // 03.31.1981
            // 3.31.2014
            // 3.2.1981
            // 3.2.81
            // 08.21.71
            // 2018.09.30
            return (Some(p), None);
        }
        DateState::DigitWsMoYear => {
            // 2 Jan 2018
            // 2 Jan 18
            // 2 Jan 2018 23:59
            // 02 Jan 2018 23:59
            // 12 Feb 2006, 19:17
            return (Some(p), None);
        }
        DateState::DigitWsMolong => {
            // 18 January 2018
            // 8 January 2018
            if p.daylen == 2 {
                p.format = b"02 January 2006".to_vec();
                return (Some(p), None);
            }
            p.format = b"2 January 2006".to_vec();
            return (Some(p), None); // parse("2 January 2006", datestr, loc)
        }
        DateState::AlphaWsMonth | DateState::AlphaWsDigitMoreWs => {
            // April 8, 2009
            // oct 1, 1970
            p.yearlen = i - p.yeari;
            p.set_year();
            return (Some(p), None);
        }
        DateState::AlphaWsMonthMore
        | DateState::AlphaWsDigitMoreWsYear
        | DateState::AlphaWsAlpha
        | DateState::AlphaWsDigit
        | DateState::AlphaWsDigitYearmaybe
        | DateState::DigitSlash
        | DateState::DigitSlashAlpha
        | DateState::DigitYearSlash
        | DateState::DigitColon
        | DateState::WeekdayComma
        | DateState::WeekdayAbbrevComma => {
            // May 8, 2009 5:57:51 PM
            // Jun 7, 2005, 05:57:51
            // 3/1/2014
            // 10/13/2014
            // 01/02/2006
            // 03/Jun/2014
            // 2014/10/13
            // 3:1:2014
            // 10:13:2014
            // 01:02:2006
            // 2014:10:13
            // Monday, 02 Jan 2006 15:04:05 -0700
            // Monday, 02 Jan 2006 15:04:05 +0100
            // Monday, 02-Jan-06 15:04:05 MST
            // Mon, 02-Jan-06 15:04:05 MST
            // Mon, 02 Jan 2006 15:04:05 MST
            return (Some(p), None);
        }
        DateState::DigitChineseYear => {
            // dateDigitChineseYear
            //   2014年04月08日
            p.format = "2006年01月02日".as_bytes().to_vec();
            return (Some(p), None);
        }
        DateState::DigitChineseYearWs => {
            p.format = "2006年01月02日 15:04:05".as_bytes().to_vec();
            return (Some(p), None);
        }
        _ => {}
    }

    (None, Some(unknown_err(datestr)))
}

/// Go's `parser`. Exposed only for the port of dateparse's own tests
/// ([`internal`]); not part of the API.
#[doc(hidden)]
#[derive(Clone)]
pub struct Parser {
    loc: Option<Location>,
    prefer_month_first: bool,
    retry_ambiguous_date_with_swap: bool,
    ambiguous_md: bool,
    state_date: DateState,
    state_time: TimeState,
    format: Vec<u8>,
    datestr: Vec<u8>,
    full_month: Vec<u8>,
    skip: i64,
    extra: i64,
    part1_len: i64,
    yeari: i64,
    yearlen: i64,
    moi: i64,
    molen: i64,
    dayi: i64,
    daylen: i64,
    houri: i64,
    hourlen: i64,
    mini: i64,
    minlen: i64,
    seci: i64,
    seclen: i64,
    msi: i64,
    mslen: i64,
    offseti: i64,
    tzi: i64,
    tzlen: i64,
    t: Option<Time>,
}

impl Parser {
    /// Go's `newParser`.
    fn new(date_str: &[u8], loc: Option<&Location>, opts: &[ParserOption]) -> Parser {
        let mut p = Parser {
            loc: loc.cloned(),
            prefer_month_first: true,
            retry_ambiguous_date_with_swap: false,
            ambiguous_md: false,
            state_date: DateState::Start,
            state_time: TimeState::Ignore,
            format: date_str.to_vec(),
            datestr: date_str.to_vec(),
            full_month: Vec::new(),
            skip: 0,
            extra: 0,
            part1_len: 0,
            yeari: 0,
            yearlen: 0,
            moi: 0,
            molen: 0,
            dayi: 0,
            daylen: 0,
            houri: 0,
            hourlen: 0,
            mini: 0,
            minlen: 0,
            seci: 0,
            seclen: 0,
            msi: 0,
            mslen: 0,
            offseti: 0,
            tzi: 0,
            tzlen: 0,
            t: None,
        };

        // allow the options to mutate the parser fields from their defaults
        for option in opts {
            match *option {
                ParserOption::PreferMonthFirst(v) => p.prefer_month_first = v,
                ParserOption::RetryAmbiguousDateWithSwap(v) => {
                    p.retry_ambiguous_date_with_swap = v;
                }
            }
        }
        p
    }

    /// The `moi` field: where the month starts.
    pub fn moi(&self) -> i64 {
        self.moi
    }

    /// The `dayi` field: where the day starts.
    pub fn dayi(&self) -> i64 {
        self.dayi
    }

    /// The `datestr` field: the input being parsed.
    pub fn datestr(&self) -> &[u8] {
        &self.datestr
    }

    /// The `format` field: the layout being built.
    pub fn format(&self) -> &[u8] {
        &self.format
    }

    fn next_is(&self, i: i64, b: u8) -> bool {
        golen(&self.datestr) > i + 1 && self.datestr[ix(i + 1)] == b
    }

    /// Go's `set`: writes val over the layout at start, unless it does not
    /// fit.
    pub fn set(&mut self, start: i64, val: &str) {
        if start < 0 {
            return;
        }
        if golen(&self.format) < start + golen(val.as_bytes()) {
            return;
        }
        let start = ix(start);
        self.format[start..start + val.len()].copy_from_slice(val.as_bytes());
    }

    /// Go's `setMonth`.
    pub fn set_month(&mut self) {
        if self.molen == 2 {
            self.set(self.moi, "01");
        } else if self.molen == 1 {
            self.set(self.moi, "1");
        }
    }

    /// Go's `setDay`.
    pub fn set_day(&mut self) {
        if self.daylen == 2 {
            self.set(self.dayi, "02");
        } else if self.daylen == 1 {
            self.set(self.dayi, "2");
        }
    }

    fn set_year(&mut self) {
        if self.yearlen == 2 {
            self.set(self.yeari, "06");
        } else if self.yearlen == 4 {
            self.set(self.yeari, "2006");
        }
    }

    fn coalesce_date(&mut self, end: i64) {
        if self.yeari > 0 {
            if self.yearlen == 0 {
                self.yearlen = end - self.yeari;
            }
            self.set_year();
        }
        if self.moi > 0 && self.molen == 0 {
            self.molen = end - self.moi;
            self.set_month();
        }
        if self.dayi > 0 && self.daylen == 0 {
            self.daylen = end - self.dayi;
            self.set_day();
        }
    }

    /// Go's `ts`: the time indices, for debugging.
    pub fn ts(&self) -> String {
        format!(
            "h:({}:{}) m:({}:{}) s:({}:{})",
            self.houri, self.hourlen, self.mini, self.minlen, self.seci, self.seclen
        )
    }

    /// Go's `ds`: the input and the date indices, for debugging.
    pub fn ds(&self) -> Vec<u8> {
        let mut b = self.datestr.clone();
        b.extend_from_slice(
            format!(
                " d:({}:{}) m:({}:{}) y:({}:{})",
                self.dayi, self.daylen, self.moi, self.molen, self.yeari, self.yearlen
            )
            .as_bytes(),
        );
        b
    }

    fn coalesce_time(&mut self, end: i64) {
        // 03:04:05
        // 15:04:05
        // 3:04:05
        // 3:4:5
        // 15:04:05.00
        if self.houri > 0 {
            if self.hourlen == 2 {
                self.set(self.houri, "15");
            } else if self.hourlen == 1 {
                self.set(self.houri, "3");
            }
        }
        if self.mini > 0 {
            if self.minlen == 0 {
                self.minlen = end - self.mini;
            }
            if self.minlen == 2 {
                self.set(self.mini, "04");
            } else {
                self.set(self.mini, "4");
            }
        }
        if self.seci > 0 {
            if self.seclen == 0 {
                self.seclen = end - self.seci;
            }
            if self.seclen == 2 {
                self.set(self.seci, "05");
            } else {
                self.set(self.seci, "5");
            }
        }

        if self.msi > 0 {
            for i in 0..self.mslen {
                self.format[ix(self.msi + i)] = b'0';
            }
        }
    }

    fn set_full_month(&mut self, month: &[u8]) {
        if self.moi == 0 {
            self.format = [b"January".as_slice(), &self.format[month.len()..]].concat();
        }
    }

    fn trim_extra(&mut self) {
        if self.extra > 0 && golen(&self.format) > self.extra {
            self.format.truncate(ix(self.extra));
            self.datestr = self.datestr[..ix(self.extra)].to_vec();
        }
    }

    /// Go's `parse`. It changes the parser (the full month name and the
    /// skipped weekday are applied each time), as in Go.
    fn parse(&mut self) -> Result<Time, ParseError> {
        if let Some(t) = &self.t {
            return Ok(t.clone());
        }
        if !self.full_month.is_empty() {
            let month = self.full_month.clone();
            self.set_full_month(&month);
        }
        if self.skip > 0 && golen(&self.format) > self.skip {
            self.format = self.format[ix(self.skip)..].to_vec();
            self.datestr = self.datestr[ix(self.skip)..].to_vec();
        }

        match &self.loc {
            None => gotime::parse(&self.format, &self.datestr),
            Some(loc) => gotime::parse_in_location(&self.format, &self.datestr, loc),
        }
    }
}

fn is_day(alpha: &[u8]) -> bool {
    DAYS.contains(&alpha)
}

fn is_month_full(alpha: &[u8]) -> bool {
    MONTHS.contains(&alpha)
}

/// Go's `strings.ToLower(s)` where that is all ASCII, the only case in which
/// it can equal a day or month name; None otherwise. Each rune of s becomes
/// one byte, so `İ` (two bytes) lowers to `i` and the result is shorter than
/// s, which [`Parser::set_full_month`] then cuts by.
fn to_lower(s: &[u8]) -> Option<Vec<u8>> {
    let mut out = Vec::with_capacity(s.len());
    let mut i = 0;
    while i < s.len() {
        let (r, size) = decode_rune(&s[i..]);
        if r < 0x80 {
            out.push((r as u8).to_ascii_lowercase());
        } else {
            let &(_, lower) = tables::LOWER_TO_ASCII.iter().find(|&&(c, _)| c == r)?;
            out.push(lower);
        }
        i += size;
    }
    Some(out)
}

fn in_table(table: &[(u32, u32)], r: char) -> bool {
    let r = u32::from(r);
    table
        .binary_search_by(|&(lo, hi)| {
            if hi < r {
                Ordering::Less
            } else if lo > r {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

/// Go's `unicode.IsLetter`.
fn is_letter(r: char) -> bool {
    in_table(tables::LETTER, r)
}

/// Go's `unicode.IsDigit`.
fn is_digit(r: char) -> bool {
    in_table(tables::DIGIT, r)
}

/// Go's `strconv.ParseInt(s, 10, 64)`, None where it fails.
fn parse_int(s: &[u8]) -> Option<i64> {
    let (neg, digits) = match s.first() {
        Some(b'+') => (false, &s[1..]),
        Some(b'-') => (true, &s[1..]),
        _ => (false, s),
    };
    if digits.is_empty() {
        return None;
    }
    let mut n: u64 = 0;
    for &c in digits {
        if !c.is_ascii_digit() {
            return None;
        }
        n = n.checked_mul(10)?.checked_add(u64::from(c - b'0'))?;
    }
    if neg {
        (n <= 1 << 63).then(|| (n as i64).wrapping_neg())
    } else {
        i64::try_from(n).ok()
    }
}


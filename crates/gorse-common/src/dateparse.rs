/// A dateparse error. [`Error::error_bytes`] is Go's `err.Error()` byte for
/// byte; `Display` shows the same text, with invalid UTF-8 replaced.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// No layout fits the input (Go's `unknownErr`):
    /// `Could not find format for "…"`.
    UnknownFormat(Vec<u8>),
    /// A run of digits shorter than four bytes:
    /// `unrecognized format, too short …`.
    TooShort(Vec<u8>),
    /// A numeric zone offset that is not 2 or 4 digits:
    /// `TZ offset not recognized "…" near "…" (…)`.
    TzOffset {
        /// The input being parsed.
        datestr: Vec<u8>,
        /// The input from the offset on.
        near: Vec<u8>,
    },
    /// [`parse_strict`] on a date that could be mm/dd or dd/mm (Go's
    /// `ErrAmbiguousMMDD`).
    AmbiguousMmdd,
    /// The layout dateparse chose does not parse the input.
    Parse(ParseError),
}

impl Error {
    /// Go's `err.Error()`. It holds the input as given, so it is not always
    /// UTF-8.
    pub fn error_bytes(&self) -> Vec<u8> {
        match self {
            Error::UnknownFormat(datestr) => {
                let mut b = b"Could not find format for ".to_vec();
                gostrconv::append_quote(&mut b, datestr);
                b
            }
            Error::TooShort(datestr) => {
                let mut b = b"unrecognized format, too short ".to_vec();
                b.extend_from_slice(datestr);
                b
            }
            Error::TzOffset { datestr, near } => {
                let mut b = b"TZ offset not recognized ".to_vec();
                gostrconv::append_quote(&mut b, datestr);
                b.extend_from_slice(b" near ");
                gostrconv::append_quote(&mut b, near);
                b.extend_from_slice(b" (must be 2 or 4 digits optional colon)");
                b
            }
            Error::AmbiguousMmdd => ERR_AMBIGUOUS_MMDD.as_bytes().to_vec(),
            Error::Parse(e) => e.to_string().into_bytes(),
        }
    }
}


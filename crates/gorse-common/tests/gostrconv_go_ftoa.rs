    #[test]
    fn itoa() {
        for &(input, base, want) in ITOB64TESTS {
            assert_eq!(format_int(input, base), want, "FormatInt({input}, {base})");
            if input >= 0 {
                assert_eq!(
                    format_uint(input as u64, base),
                    want,
                    "FormatUint({input}, {base})"
                );
            }
        }
    }


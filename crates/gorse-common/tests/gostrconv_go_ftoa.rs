    #[test]
    fn ftoa() {
        for (f, fmt, prec, want) in ftoatests() {
            let got = format_float(f, fmt, prec, 64);
            assert_eq!(got, want, "testN=64 {f} {} {prec}", char::from(fmt));
            if f64::from(f as f32) == f && fmt != b'b' {
                if f == 5.960464477539063e-08 {
                    // This test is an exact float32 but asking for float64
                    // precision in the string; Go skips it.
                    continue;
                }
                let got = format_float(f, fmt, prec, 32);
                assert_eq!(got, want, "testN=32 {f} {} {prec}", char::from(fmt));
            }
        }
    }

    #[test]
    fn ftoa_powers_of_two() {
        for exp in -2048..=2048 {
            let f = 2f64.powi(exp);
            if !f.is_infinite() {
                let s = format_float(f, b'e', -1, 64);
                let (x, _) = parse_float(&s, 64);
                assert_eq!(x, f, "failed roundtrip {f} => {s} => {x}");
            }
            let f32 = f as f32;
            if !f32.is_infinite() {
                let s = format_float(f64::from(f32), b'e', -1, 32);
                let (x, _) = parse_float(&s, 32);
                assert_eq!(x as f32, f32, "failed roundtrip {f32} => {s} => {x}");
            }
        }
    }


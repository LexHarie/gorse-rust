    #[test]
    fn test_url_clone() {
        let tests = [
            // ("nil", nil): a Url cannot be nil.
            ("zero value", url! {}),
            (
                "Populated but nil .User",
                url! {
                    user: None,
                    host: "foo",
                    path: "/path",
                    raw_query: "a=b",
                },
            ),
            (
                "non-nil .User",
                url! {
                    user: user("user"),
                    host: "foo",
                    path: "/path",
                    raw_query: "a=b",
                },
            ),
            (
                "non-nil .User: user and password set",
                url! {
                    user: user_password("user", "password"),
                    host: "foo",
                    path: "/path",
                    raw_query: "a=b",
                },
            ),
        ];

        for (name, input) in tests {
            // 1. The cloned URL must always deep equal the input, but never
            // the same pointer. (A Rust clone is a separate value.)
            let mut cloned = input.clone();
            assert!(
                input == cloned,
                "{name}: Differing values\noriginal: {}\ncloned: {}",
                q(input.string()),
                q(cloned.string())
            );

            // 2. Test out malleability of URL fields.
            cloned.scheme = b"https".to_vec();
            assert!(
                cloned.scheme != input.scheme,
                "{name}: Inconsistent state: cloned.scheme changed and reflected in the input's scheme"
            );
            assert!(
                input != cloned,
                "{name}: Inconsistent state: cloned and input are somehow the same"
            );

            // 3. Ensure that the .User object deep equals but not the same
            // pointer. (The clone's Userinfo is its own value.)
            assert!(
                input.user == cloned.user,
                "{name}: Differing .User\noriginal: {}\ncloned: {}",
                q(input.string()),
                q(cloned.string())
            );
        }
    }

    #[test]
    fn test_values_clone() {
        let tests = [
            // ("nil", nil): a nil Values is the empty Values.
            ("nil", Values::default()),
            ("empty", values! {}),
            // ("1 key, nil values", Values{"1": nil}): a nil slice is an
            // empty Vec.
            ("1 key, nil values", values! {"1": []}),
            ("1 key, no values", values! {"1": []}),
            ("1 key, some values", values! {"1": ["a", "b"]}),
            (
                "multiple keys, diverse values",
                values! {"1": ["a", "b"], "X": [], "B": ["abcdefghi"]},
            ),
        ];

        for (name, input) in tests {
            // The cloned map must always deep equal the input.
            let mut cloned1 = input.clone();
            assert!(input == cloned1, "{name}: reflect.DeepEqual failed");

            // (Go returns here when both are nil and fails when one of two
            // empty maps is nil; the empty Values covers both.)

            // Test out malleability of values.
            cloned1
                .0
                .insert(b"XXXXXXXXXXX".to_vec(), vec![b"a".to_vec(), b"b".to_vec()]);
            assert!(
                input != cloned1,
                "{name}: Inconsistent state: cloned and input are somehow the same"
            );

            // Ensure that we can correctly invoke some methods like .Add
            let mut cloned2 = input.clone();
            assert!(input == cloned2, "{name}: reflect.DeepEqual failed");
            cloned2.add("a", "A");
            assert!(
                cloned2.has("a"),
                "{name}: Cloned doesn't have the desired key: a"
            );
            assert!(
                cloned2.has("a"),
                "{name}: Cloned doesn't have the desired key: a"
            );
            // Assert that any changes to the clone did not change the original.
            assert!(
                input != cloned2,
                "{name}: reflect.DeepEqual unexpectedly passed after modify cloned"
            );
            cloned2.del("a");
            // Assert that reverting the clone's changes bring it back to original state.
            assert!(input == cloned2, "{name}: reflect.DeepEqual failed");

            let mut cloned3 = input.clone();
            // (Go takes whichever key its map iteration yields first; the
            // first key in order is one such choice.)
            let Some(key0) = cloned3.0.keys().next().cloned() else {
                continue;
            };
            // Test modifying the actual slice.
            let vs = cloned3.0.get_mut(&key0).expect("key0");
            if vs.is_empty() {
                vs.push(b"golang".to_vec());
            } else {
                vs[0] = b"directly modified".to_vec();
                let (got, want) = (cloned3.get(&key0), "directly modified");
                assert!(
                    got == want.as_bytes(),
                    "{name}: Get failed:\n\tGot:  {}\n\tWant: {}",
                    q(got),
                    q(want)
                );
            }
            assert!(
                input != cloned3,
                "{name}: reflect.DeepEqual unexpectedly passed after modify cloned"
            );

            // Try out also with .Set.
            let mut cloned4 = input.clone();
            assert!(input == cloned4, "{name}: reflect.DeepEqual failed");
            cloned4.set(&key0, "good night");
            assert!(
                input != cloned4,
                "{name}: reflect.DeepEqual unexpectedly passed after modify cloned"
            );
            let (got, want) = (cloned4.get(&key0), "good night");
            assert!(
                got == want.as_bytes(),
                "{name}: Get failed:\n\tGot:  {}\n\tWant: {}",
                q(got),
                q(want)
            );
        }
    }


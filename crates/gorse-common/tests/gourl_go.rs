    fn test_parse_query_limits() {
        let default_max_params = internal::DEFAULT_MAX_PARAMS as usize;
        // (params, godebug, wantErr)
        let tests: &[(usize, &str, bool)] = &[
            (10, "", false),
            (default_max_params, "", false),
            (default_max_params + 1, "", true),
            (10, "urlmaxqueryparams=9", true),
            (default_max_params + 1, "urlmaxqueryparams=0", false),
        ];
        if !is_child() {
            for (i, &(_, godebug, _)) in tests.iter().enumerate() {
                // t.Setenv("GODEBUG", test.godebug)
                let i = i.to_string();
                run_in_child(
                    "gourl::test_parse_query_limits",
                    &[("GODEBUG", Some(godebug)), (LIMITS_CASE_ENV, Some(&i))],
                );
            }
            return;
        }
        let i: usize = std::env::var(LIMITS_CASE_ENV)
            .expect("case index")
            .parse()
            .expect("case index");
        let (params, godebug, want_err) = tests[i];
        let mut want = Values::default();
        let mut b = String::new();
        for i in 0..params {
            if i > 0 {
                b.push('&');
            }
            let p = format!("p{i}");
            b.push_str(&p);
            want.0.insert(p.into_bytes(), vec![Vec::new()]);
        }
        let query = b;
        let (got, err) = parse_query(&query);
        let got_err = err.is_some();
        assert!(
            got_err == want_err,
            "GODEBUG={godebug} ParseQuery({params} params) = {}, want error: {want_err}",
            err.map(|e| e.to_string()).unwrap_or("<nil>".to_owned())
        );
        if err.is_some() {
            return;
        }
        assert!(
            got.len() == params,
            "GODEBUG={godebug} ParseQuery({params} params): got {} params, want {params}",
            got.len()
        );
        // (Go builds want but compares only the lengths; comparing the
        // values as well is stricter.)
        assert_eq!(got, want);
    }


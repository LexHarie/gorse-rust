    /// Converts a value in a test table to the type of a [`Url`] field.
    trait Field<T> {
        fn field(self) -> T;
    }

    impl Field<Vec<u8>> for &str {
        fn field(self) -> Vec<u8> {
            self.as_bytes().to_vec()
        }
    }

    impl Field<bool> for bool {
        fn field(self) -> bool {
            self
        }
    }

    impl Field<Option<Userinfo>> for Userinfo {
        fn field(self) -> Option<Userinfo> {
            Some(self)
        }
    }

    impl Field<Option<Userinfo>> for Option<Userinfo> {
        fn field(self) -> Option<Userinfo> {
            self
        }
    }

    /// Go's `&URL{Field: value, ...}`.
    macro_rules! url {
        ($($field:ident: $value:expr),* $(,)?) => {
            Url {
                $($field: Field::field($value),)*
                ..Url::default()
            }
        };
    }

    /// Go's `Values{"k": {"v", ...}, ...}`.
    macro_rules! values {
        ($($key:literal: [$($value:literal),* $(,)?]),* $(,)?) => {{
            #[allow(unused_mut, reason = "an empty literal adds nothing")]
            let mut v = Values::default();
            $(
                v.0.insert(
                    $key.as_bytes().to_vec(),
                    vec![$($value.as_bytes().to_vec()),*],
                );
            )*
            v
        }};
    }

    /// `%q` of bytes, for messages.
    fn q(b: impl AsRef<[u8]>) -> String {
        quote(b)
    }

    /// Go's `strings.ReplaceAll` on bytes.
    fn replace_all(s: &[u8], old: &[u8], new: &[u8]) -> Vec<u8> {
        let mut out = Vec::with_capacity(s.len());
        let mut i = 0;
        while i < s.len() {
            if s[i..].starts_with(old) {
                out.extend_from_slice(new);
                i += old.len();
            } else {
                out.push(s[i]);
                i += 1;
            }
        }
        out
    }

    /// Go's `QueryUnescape` and `PathUnescape` results as Go returns them:
    /// the empty string with the error.
    fn go_result<E>(r: Result<Vec<u8>, E>) -> (Vec<u8>, Option<E>) {
        match r {
            Ok(v) => (v, None),
            Err(e) => (Vec::new(), Some(e)),
        }
    }


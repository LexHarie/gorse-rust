    /// more useful string for debugging than fmt's struct printer
    fn ufmt(u: &Url) -> String {
        let (user, pass) = match &u.user {
            None => ("<nil>".to_owned(), "<nil>".to_owned()),
            Some(ui) => {
                let (p, ok) = ui.password();
                (q(ui.username()), if ok { q(p) } else { "<nil>".to_owned() })
            }
        };
        format!(
            "opaque={}, scheme={}, user={user}, pass={pass}, host={}, path={}, rawpath={}, rawq={}, frag={}, rawfrag={}, forcequery={}, omithost={}",
            q(&u.opaque),
            q(&u.scheme),
            q(&u.host),
            q(&u.path),
            q(&u.raw_path),
            q(&u.raw_query),
            q(&u.fragment),
            q(&u.raw_fragment),
            u.force_query,
            u.omit_host
        )
    }

    #[test]
    fn test_parse() {
        for (input, out, _) in urltests() {
            if input.is_empty() {
                continue;
            }
            let u = parse(input).unwrap_or_else(|err| {
                panic!("Parse({}) returned error {err}", q(input));
            });
            assert!(
                u == out,
                "Parse({}):\n\tgot  {}\n\twant {}\n",
                q(input),
                ufmt(&u),
                ufmt(&out)
            );
        }
    }

